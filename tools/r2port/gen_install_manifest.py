#!/usr/bin/env python3
"""Regenerates engine/filesystem/r2_install_manifest.inc from a Titanfall 2 install.

The R2 map provider needs, for the 20 allowlisted maps, the map package files (directory VPK and every
content chunk, which hold the BSP and entity files), the shared mp_common / frontend packages and the RPak
families it decodes materials from. DLC 5 ("dlc5_enabled") is only claimed when every file listed here exists
in the player's install with at least the recorded size. Starpaks are deliberately not listed: players delete
the optional HD ones to free disk space, and the RPak decoder tolerates their absence.

Usage: gen_install_manifest.py <Titanfall2 install root> [output .inc]
Keep the map list in sync with kR2MapAllowlist in engine/filesystem/r2_map_provider.cpp.
"""
import os
import re
import sys

MAPS = [
    "mp_black_water_canal", "mp_coliseum", "mp_coliseum_column", "mp_colony02", "mp_complex3",
    "mp_crashsite3", "mp_drydock", "mp_eden", "mp_forwardbase_kodai", "mp_glitch", "mp_grave",
    "mp_homestead", "mp_lf_deck", "mp_lf_meadow", "mp_lf_stacks", "mp_lf_township", "mp_lf_traffic",
    "mp_lf_uma", "mp_relic02", "mp_thaw",
]
RPAK_FAMILIES = ("common", "particle", "patch")


def main():
    if len(sys.argv) < 2:
        print(__doc__)
        return 2
    root = sys.argv[1]
    out = sys.argv[2] if len(sys.argv) > 2 else os.path.join(
        os.path.dirname(__file__), "..", "..", "engine", "filesystem", "r2_install_manifest.inc")

    vpk_dir = os.path.join(root, "vpk")
    prefixes = [
        "englishclient_mp_common.bsp.pak000_dir", "client_mp_common.bsp.pak000_",
        "englishclient_frontend.bsp.pak000_dir", "client_frontend.bsp.pak000_",
    ]
    for name in MAPS:
        prefixes += ["englishclient_%s.bsp.pak000_dir" % name, "client_%s.bsp.pak000_" % name]

    entries = []
    for f in sorted(os.listdir(vpk_dir)):
        if f.endswith(".vpk") and any(f.startswith(p) for p in prefixes):
            entries.append(("vpk/" + f, os.path.getsize(os.path.join(vpk_dir, f))))

    pak_dir = os.path.join(root, "r2", "paks", "Win64")
    map_keys = tuple("mp_" + m[3:] for m in MAPS)
    for f in sorted(os.listdir(pak_dir)):
        if not f.endswith(".rpak"):
            continue
        base = re.split(r"\(", f)[0]
        if base.startswith(RPAK_FAMILIES) or any(base == k or base.startswith(k + "_") for k in map_keys):
            entries.append(("r2/paks/Win64/" + f, os.path.getsize(os.path.join(pak_dir, f))))

    version = ""
    gv = os.path.join(root, "gameversion.txt")
    if os.path.exists(gv):
        version = open(gv).read().strip()
    with open(out, "w", newline="\n") as fh:
        fh.write("// Generated by tools/r2port/gen_install_manifest.py from Titanfall 2 %s. Do not edit.\n" % version)
        fh.write("// { path relative to the install root, minimum size in bytes }\n")
        for path, size in entries:
            fh.write('{ "%s", %dull },\n' % (path, size))
    print("wrote %d entries (%.2f GB) to %s" % (len(entries), sum(s for _, s in entries) / 1e9, out))
    return 0


if __name__ == "__main__":
    sys.exit(main())
