#!/usr/bin/env python
"""Generates engine/r2port/shaders/r2_shader_source_postfx.h: the r1d_post pixel shader (R2-style display curve plus RCAS
sharpening) with the display transfer table baked in.

Curve source: FlatLook's exposure-ladder fit (maps/flat/responses.json, repeated below): the display value d (0..255) as a
function of the relative linear radiance for R1 (about L^0.57 everywhere) and for R2 (near linear in the shadows, filmic
roll-off in the highlights), both anchored at d = 92. The curve maps an R1 display value to the display value R2 shows for
the same radiance: invert R1 (d -> ln L), add SHIFT (the exposure offset between the two engines, fitted to the matched
kodai pixel pairs `F_R1_to_R2_fixed_exposure`), apply R2 (ln L -> d). Below KNEE the table is a straight ramp through the
origin because the ladder has no data there; the result is forced monotone and clamped to 0..255.

Usage: python tools/r2port/make_display_curve.py [--shift S] [--print] [--out path]
Needs numpy and scipy (PCHIP interpolation keeps both responses monotone between the ladder knots).
"""
import argparse
import os
import sys

import numpy as np
from scipy.interpolate import PchipInterpolator

KNOTS_D = [2.0, 4.0, 7.0, 11.0, 16.0, 22.0, 29.0, 37.0, 46.0, 56.0, 67.0, 79.0, 92.0, 106.0, 121.0, 137.0, 154.0, 172.0, 190.0, 208.0, 226.0, 245.0]
R1_LNL = [-4.679497, -4.235229, -3.790961, -3.346693, -2.90347, -2.464838, -2.036778, -1.626837, -1.242319, -0.88667, -0.561042, -0.26668, 0.0, 0.245076, 0.473598, 0.6878, 0.887395, 1.073744, 1.249655, 1.419116, 1.586519, 1.753921]
R2_LNL = [-3.346738, -2.979898, -2.614179, -2.25842, -1.918328, -1.598546, -1.302476, -1.031639, -0.786475, -0.564533, -0.36209, -0.175611, 0.0, 0.170792, 0.343207, 0.523867, 0.717414, 0.925245, 1.14594, 1.375133, 1.607739, 1.840766]
SHIFT = 0.15
KNEE = 16.0
TABLE_SIZE = 65


def build_table(shift=SHIFT):
    r1 = PchipInterpolator(KNOTS_D, R1_LNL, extrapolate=True)
    r2_inverse = PchipInterpolator(R2_LNL, KNOTS_D, extrapolate=True)

    def transfer(d):
        return float(r2_inverse(float(r1(d)) + shift))

    knee_value = transfer(KNEE)
    values = []
    for i in range(TABLE_SIZE):
        d = i * 255.0 / (TABLE_SIZE - 1)
        values.append(knee_value * d / KNEE if d < KNEE else transfer(d))
    values = np.maximum.accumulate(np.clip(np.array(values), 0.0, 255.0))
    return values / 255.0


SHADER = r'''
// r1d_post: R2-style display curve and RCAS sharpening in one full-screen pass (generated by
// tools/r2port/make_display_curve.py, do not edit the table by hand).
// Resources (screenspace_general convention): t0 = $basetexture = _rt_FullFrameFB holding the final image (1:1 texels, read
// with Load), b0 = the 20 floats $c0_x .. $c4_w:
//   c0.x  sharpen amount 0..1 (RCAS lobe scale, 0 = no sharpening)
//   c0.y  sharpen denoise 0..1 (scale of RCAS's noise attenuation, 0.5 = AMD's FSR_RCAS_DENOISE)
//   c0.z  sharpen width in pixels (tap spacing, rounded, >= 1)
//   c0.w  source encoding: < 0.5 the texture holds display-encoded values, >= 0.5 it holds linear values (sRGB view)
//   c1.x  display curve strength 0..1 (0 = identity)
//   c1.y  view width in pixels, c1.z view height in pixels (taps clamp to this rectangle)
// RCAS follows AMD FidelityFX FSR 1 (ffx_fsr1.h v1.20210629, MIT licence): 5-tap cross, luma-proxy noise detector,
// per-channel clip-free lobe, limit 0.25 - 1/16, output (lobe*(n+e+w+s)+m)/(4*lobe+1). It runs after the curve.

cbuffer CBufPost : register(b0)
{
    float4 c[5];
};

Texture2D<float4> Src : register(t0);

static const float kCurve[65] = {
@TABLE@
};

#define RCAS_LIMIT (0.25 - 1.0 / 16.0)

float3 Curve(float3 v)
{
    float3 x = saturate(v) * 64.0;
    int3 i = min(int3(x), int3(63, 63, 63));
    float3 f = x - float3(i);
    float3 a = float3(kCurve[i.x], kCurve[i.y], kCurve[i.z]);
    float3 b = float3(kCurve[i.x + 1], kCurve[i.y + 1], kCurve[i.z + 1]);
    return lerp(v, lerp(a, b, f), saturate(c[1].x));
}

float3 ToEncoded(float3 v)
{
    v = saturate(v);
    if (c[0].w < 0.5)
        return v;
    return v <= 0.0031308 ? v * 12.92 : 1.055 * pow(v, 1.0 / 2.4) - 0.055;
}

float3 FromEncoded(float3 v)
{
    if (c[0].w < 0.5)
        return v;
    return v <= 0.04045 ? v / 12.92 : pow((v + 0.055) / 1.055, 2.4);
}

float3 Fetch(int2 p, int2 maxp, bool useCurve)
{
    float3 v = ToEncoded(Src.Load(int3(clamp(p, int2(0, 0), maxp), 0)).rgb);
    return useCurve ? Curve(v) : v;
}

float4 PSMain(float4 sv : SV_Position) : SV_Target
{
    uint tw, th;
    Src.GetDimensions(tw, th);
    const int2 maxp = min(int2(int(c[1].y + 0.5) - 1, int(c[1].z + 0.5) - 1), int2(int(tw) - 1, int(th) - 1));
    const int2 sp = int2(sv.xy);
    const bool useCurve = c[1].x > 0.0;
    const float amount = saturate(c[0].x);

    const float4 src = Src.Load(int3(clamp(sp, int2(0, 0), maxp), 0));
    const float3 e = useCurve ? Curve(ToEncoded(src.rgb)) : ToEncoded(src.rgb);
    if (amount <= 0.0)
        return float4(FromEncoded(e), src.a);

    const int step = max(1, int(c[0].z + 0.5));
    const float3 b = Fetch(sp + int2(0, -step), maxp, useCurve);
    const float3 d = Fetch(sp + int2(-step, 0), maxp, useCurve);
    const float3 f = Fetch(sp + int2(step, 0), maxp, useCurve);
    const float3 h = Fetch(sp + int2(0, step), maxp, useCurve);

    // Luma times 2.
    const float bL = b.b * 0.5 + (b.r * 0.5 + b.g);
    const float dL = d.b * 0.5 + (d.r * 0.5 + d.g);
    const float eL = e.b * 0.5 + (e.r * 0.5 + e.g);
    const float fL = f.b * 0.5 + (f.r * 0.5 + f.g);
    const float hL = h.b * 0.5 + (h.r * 0.5 + h.g);

    // Noise detection: how far the centre is from the mean of its four neighbours, relative to the local range.
    float nz = 0.25 * bL + 0.25 * dL + 0.25 * fL + 0.25 * hL - eL;
    const float range = max(max(max(bL, dL), max(eL, fL)), hL) - min(min(min(bL, dL), min(eL, fL)), hL);
    nz = saturate(abs(nz) * rcp(max(range, 1e-6)));
    nz = 1.0 - saturate(c[0].y) * nz;

    // Min and max of the ring.
    const float3 mn4 = min(min(min(b, d), f), h);
    const float3 mx4 = max(max(max(b, d), f), h);

    // Largest negative lobe that cannot clip at 0 or at 1.
    const float3 hitMin = min(mn4, e) * rcp(4.0 * mx4 + 1e-7);
    const float3 hitMax = (1.0 - max(mx4, e)) * rcp(4.0 * mn4 - 4.0 - 1e-7);
    const float3 lobeC = max(-hitMin, hitMax);
    float lobe = max(-RCAS_LIMIT, min(max(max(lobeC.r, lobeC.g), lobeC.b), 0.0)) * amount;
    lobe *= nz;

    const float3 outc = saturate((lobe * b + lobe * d + lobe * h + lobe * f + e) * rcp(4.0 * lobe + 1.0));
    return float4(FromEncoded(outc), src.a);
}
'''


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--shift', type=float, default=SHIFT)
    parser.add_argument('--print', action='store_true', help='print the transfer table as display values and exit')
    parser.add_argument('--out', default=os.path.join(os.path.dirname(__file__), '..', '..', 'engine', 'r2port', 'shaders', 'r2_shader_source_postfx.h'))
    args = parser.parse_args()

    table = build_table(args.shift)
    if args.print:
        for i, v in enumerate(table):
            d = i * 255.0 / (TABLE_SIZE - 1)
            print('%6.1f -> %6.1f' % (d, v * 255.0))
        return 0

    rows = []
    for i in range(0, TABLE_SIZE, 8):
        rows.append('    ' + ', '.join('%.6f' % v for v in table[i:i + 8]) + ',')
    source = SHADER.replace('@TABLE@', '\n'.join(rows).rstrip(','))
    header = (
        '#pragma once\n\n'
        '// Generated by tools/r2port/make_display_curve.py (shift %.3f): the r1d_post shader, see docs/r2port.md "Post effects".\n'
        '// Keep the literal below 16 KB (MSVC limit for one string literal).\n\n'
        'namespace r2port::shaders {\n\n'
        'inline constexpr const char kPostfxSource[] = R"HLSL(%s)HLSL";\n\n'
        '} // namespace r2port::shaders\n' % (args.shift, source))
    with open(args.out, 'w', newline='\n') as handle:
        handle.write(header)
    print('wrote', os.path.normpath(args.out), len(source), 'bytes of HLSL')
    return 0


if __name__ == '__main__':
    sys.exit(main())
