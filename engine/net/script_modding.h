#pragma once

// Pure classification rules for "is this game / this script file modded". No engine, filesystem
// or Windows dependency: the engine-facing facts (addon directories, file hashes, loaded modules)
// are injected, so the rules are unit-testable (tests/script_modding_tests.cpp).
//
// Mods reach scripts three ways and each has its own reason:
//   addons  an enabled r1/addons/<name> directory (the supported route)
//   core    a file in the app's own r1delta tree that differs from, or is absent from, the
//           content manifest generated at release time (hand-installed mods)
//   native  a game-tree DLL that R1Delta and retail never shipped, or a shipped DLL whose bytes
//           differ from the release

#include <cstdint>
#include <functional>
#include <string>
#include <string_view>
#include <unordered_map>
#include <vector>

namespace ScriptModding
{

using ReasonMask = std::uint8_t;
constexpr ReasonMask kReasonAddons = 1;
constexpr ReasonMask kReasonCore = 2;
constexpr ReasonMask kReasonNative = 4;

// Wire names, in the order a payload lists them.
std::vector<std::string_view> ReasonNames(ReasonMask reasons);
// "addons,core", or "none".
std::string ReasonText(ReasonMask reasons);

// --- content manifest -----------------------------------------------------------------------
//
// r1delta/content_manifest.txt, generated by ci/new_content_manifest.ps1:
//   r1delta-content-manifest 1
//   S <sha256> <path>   script and menu content: scripts/vscripts/** and resource/**/*.res|*.menu
//   N <sha256> <path>   native modules: *.dll under bin, bin_nexon and bin_delta
// Paths are relative to the r1delta directory, lowercase, '/' separated. Hashes are lowercase hex.

inline constexpr std::string_view kManifestFileName = "content_manifest.txt";
inline constexpr std::string_view kManifestHeader = "r1delta-content-manifest 1";
inline constexpr std::size_t kSha256HexLength = 64;

struct Manifest
{
    std::unordered_map<std::string, std::string> content; // path -> sha256
    std::unordered_map<std::string, std::string> modules; // path -> sha256
};

// Replaces `manifest` on success. On failure `manifest` is untouched and `error` (when given)
// names the first bad line.
bool ParseManifest(std::string_view text, Manifest& manifest, std::string* error = nullptr);

// Lowercase, '\\' -> '/', leading "./" and "/" removed.
std::string NormalizePath(std::string_view path);

// True for the files the manifest tracks as content: scripts/vscripts/** and resource/**/*.res|*.menu.
bool IsTrackedContentPath(std::string_view normalizedPath);
bool IsTrackedModulePath(std::string_view normalizedPath);

// The r1delta-relative path of the file behind a callstack frame ("client/cl_player.nut" ->
// "scripts/vscripts/client/cl_player.nut"). Empty for sources that are not files ("console", "mcp").
std::string FrameContentPath(std::string_view frameSource);

enum class FileState
{
    Stock,    // present, hash matches the manifest
    Modified, // present, hash differs
    Added,    // present, not in the manifest
    Missing,  // in the manifest, not present (or no hash given)
};
FileState CompareContentFile(const Manifest& manifest, std::string_view normalizedPath,
    std::string_view sha256);

// --- frames ---------------------------------------------------------------------------------

struct FrameFacts
{
    // The relative path is a file inside an enabled addon directory.
    std::function<bool(const std::string& relativePath)> addonProvides;
    // SHA-256 (lowercase hex) of the file under the r1delta directory; false when it does not exist.
    std::function<bool(const std::string& relativePath, std::string& sha256)> hashCoreFile;
};

struct FrameVerdict
{
    bool modded = false;
    ReasonMask reasons = 0;
};

// A frame is modded when an enabled addon provides its file, or its r1delta copy differs from the
// manifest or is not in it.
FrameVerdict ClassifyFrame(const Manifest& manifest, std::string_view frameSource,
    const FrameFacts& facts);

// --- native modules -------------------------------------------------------------------------

struct ModuleInfo
{
    std::string name; // file name
    std::string path; // full path as loaded
};

struct ModuleContext
{
    std::string systemRoot;     // %SystemRoot%, normalized
    std::string gameRoot;       // directory of the running exe, normalized
    const Manifest* manifest = nullptr;
    // SHA-256 of a file on disk; false when unreadable. Null skips the byte comparison of shipped
    // modules (the crash report path, which must not hash 60 MB of DLLs).
    std::function<bool(const std::string& path, std::string& sha256)> hashFile;
};

enum class ModuleKind
{
    System,         // under the Windows directory
    Shipped,        // R1Delta payload module, bytes match the release
    Retail,         // retail Titanfall module
    Modified,       // R1Delta payload module whose bytes differ from the release
    ForeignGame,    // inside the game tree, shipped by neither R1Delta nor retail
    ForeignOther,   // outside the game tree: overlays, hooks, injected software
    Unverifiable,   // no manifest to judge against, or a shipped module that could not be read
};

ModuleKind ClassifyModule(const ModuleInfo& module, const ModuleContext& context);

// Modules that make the game's native code modded: foreign inside the game tree, or shipped
// modules that were changed.
bool IsNativeModdingKind(ModuleKind kind);

// Retail Titanfall's own module names (lowercase). Exposed for tests.
bool IsRetailModuleName(std::string_view lowerName);

} // namespace ScriptModding
