// R2 "world/atmosphere" additive sheets (godray_*, atmosphere_*) multiply a nearly flat cloud-noise texture
// (RGB about 0.66, alpha about 0.16) into per-vertex colour and alpha. R1's UnlitGeneric additive blend reads
// the texture alpha as the beam intensity, so any moment where the texture is not resident (a white,
// alpha 1 placeholder, or half uploaded data) turns the beams into hard, saturated cards or rainbow noise.
// When the texture is flat enough, bake its mean into $color/$alpha and drop the texture dependency.
struct FlatSheet {
    bool ok = false;
    double rgb[3] = {1.0, 1.0, 1.0};
    double alpha = 1.0;
};

FlatSheet flatSheetStats(const std::shared_ptr<Database>& db, const AssetRecord& texture) {
    FlatSheet flat;
    std::vector<std::uint8_t> vtf;
    std::string why;
    if (!convertTextureWithDb(db, texture, TextureOptions{}, vtf, why) || vtf.size() < 0x40) return flat;
    if (std::memcmp(vtf.data(), "VTF\0", 4) != 0) return flat;
    const std::uint32_t headerSize = u32(vtf.data() + 12);
    const std::uint32_t width = u16(vtf.data() + 16);
    const std::uint32_t height = u16(vtf.data() + 18);
    const std::uint32_t frames = u16(vtf.data() + 24);
    const std::uint32_t format = u32(vtf.data() + 0x34);
    // Only the plain RGBA8888 layout is decoded; the top mip is the last image in the file.
    if (format != 0 || frames != 1 || !width || !height || headerSize >= vtf.size()) return flat;
    const std::size_t topBytes = static_cast<std::size_t>(width) * height * 4u;
    if (vtf.size() < topBytes + headerSize) return flat;
    const std::uint8_t* top = vtf.data() + vtf.size() - topBytes;
    double sum[4] = {0, 0, 0, 0}, sumSq[4] = {0, 0, 0, 0};
    for (std::size_t i = 0; i < topBytes; i += 4)
        for (int c = 0; c < 4; ++c) {
            sum[c] += top[i + c];
            sumSq[c] += static_cast<double>(top[i + c]) * top[i + c];
        }
    const double pixels = static_cast<double>(topBytes / 4u);
    for (int c = 0; c < 4; ++c) {
        // Flat means a standard deviation of at most 0.06 on every channel (godray_generic01 and atmosphere_cloud01
        // are 0.02..0.04).
        const double mean = sum[c] / pixels;
        const double variance = std::max(0.0, sumSq[c] / pixels - mean * mean);
        if (std::sqrt(variance) > 15.3) return flat;
        if (c < 3) flat.rgb[c] = mean / 255.0; else flat.alpha = mean / 255.0;
    }
    flat.ok = true;
    return flat;
}

// Mean colour (0..255, as stored) of the smallest mip of a converted VTF: the first image after the header. Only RGBA8888 and DXT1
// layouts (what convertTextureWithDb emits for BC1 and the decoded BC7 albedo/spec textures) are read.
bool vtfSmallestMipMean(const std::vector<std::uint8_t>& vtf, double rgb[3]) {
    if (vtf.size() < 0x58 || std::memcmp(vtf.data(), "VTF\0", 4) != 0) return false;
    const std::uint32_t headerSize = u32(vtf.data() + 12);
    const std::uint32_t format = u32(vtf.data() + 0x34);
    if (headerSize >= vtf.size()) return false;
    const std::uint8_t* mip = vtf.data() + headerSize;
    const std::size_t left = vtf.size() - headerSize;
    if (format == 0 && left >= 4) {
        for (int c = 0; c < 3; ++c) rgb[c] = mip[c];
        return true;
    }
    if (format == 13 && left >= 8) {
        std::array<std::uint8_t, 64> px{};
        bcdec_bc1(mip, px.data(), 16);
        for (int c = 0; c < 3; ++c) {
            double s = 0;
            for (int p = 0; p < 16; ++p) s += px[p * 4 + c];
            rgb[c] = s / 16.0;
        }
        return true;
    }
    return false;
}

// True mean colour (0..255, as stored) of the top mip of a converted VTF (mips are stored smallest first, so the top mip is the last image
// in the file). The smallest mip cannot stand in for the mean: the converter keeps _ilm mip chains bright. Same two layouts as above.
bool vtfTopMipMean(const std::vector<std::uint8_t>& vtf, double rgb[3]) {
    if (vtf.size() < 0x58 || std::memcmp(vtf.data(), "VTF\0", 4) != 0) return false;
    const std::uint32_t width = u16(vtf.data() + 16), height = u16(vtf.data() + 18);
    const std::uint32_t format = u32(vtf.data() + 0x34);
    if (!width || !height) return false;
    double sum[3] = {0, 0, 0};
    if (format == 0) {
        const std::size_t bytes = std::size_t(width) * height * 4;
        if (vtf.size() < bytes) return false;
        const std::uint8_t* px = vtf.data() + vtf.size() - bytes;
        for (std::size_t i = 0; i < std::size_t(width) * height; ++i)
            for (int c = 0; c < 3; ++c) sum[c] += px[i * 4 + c];
        for (int c = 0; c < 3; ++c) rgb[c] = sum[c] / (double(width) * height);
        return true;
    }
    if (format == 13) {
        const std::size_t blocksX = (width + 3) / 4, blocksY = (height + 3) / 4;
        const std::size_t bytes = blocksX * blocksY * 8;
        if (vtf.size() < bytes) return false;
        const std::uint8_t* blocks = vtf.data() + vtf.size() - bytes;
        std::array<std::uint8_t, 64> px{};
        for (std::size_t b = 0; b < blocksX * blocksY; ++b) {
            bcdec_bc1(blocks + b * 8, px.data(), 16);
            for (int p = 0; p < 16; ++p)
                for (int c = 0; c < 3; ++c) sum[c] += px[p * 4 + c];
        }
        for (int c = 0; c < 3; ++c) rgb[c] = sum[c] / (double(blocksX * blocksY) * 16.0);
        return true;
    }
    return false;
}

// Share of the visible texels (alpha above 8) of a converted VTF's top mip whose alpha reaches `threshold` (0..255). Only the layouts the converter
// emits for an albedo with alpha are read: RGBA8 (format 0), DXT3 (14) and DXT5 (15); DXT1 has no alpha and anything else returns false.
bool vtfTopMipVisibleShareAtOrAbove(const std::vector<std::uint8_t>& vtf, int threshold, double& share) {
    if (vtf.size() < 0x58 || std::memcmp(vtf.data(), "VTF\0", 4) != 0) return false;
    const std::uint32_t width = u16(vtf.data() + 16), height = u16(vtf.data() + 18);
    const std::uint32_t format = u32(vtf.data() + 0x34);
    if (!width || !height) return false;
    std::uint64_t visible = 0, passing = 0;
    auto count = [&](int alpha) {
        if (alpha <= 8) return;
        ++visible;
        if (alpha >= threshold) ++passing;
    };
    if (format == 0) {
        const std::size_t bytes = std::size_t(width) * height * 4;
        if (vtf.size() < bytes) return false;
        const std::uint8_t* px = vtf.data() + vtf.size() - bytes;
        for (std::size_t i = 0; i < std::size_t(width) * height; ++i) count(px[i * 4 + 3]);
    } else if (format == 14 || format == 15) {
        const std::size_t blocksX = (width + 3) / 4, blocksY = (height + 3) / 4;
        const std::size_t bytes = blocksX * blocksY * 16;
        if (vtf.size() < bytes) return false;
        const std::uint8_t* blocks = vtf.data() + vtf.size() - bytes;
        std::array<std::uint8_t, 64> px{};
        for (std::size_t b = 0; b < blocksX * blocksY; ++b) {
            if (format == 14) bcdec_bc2(blocks + b * 16, px.data(), 16); else bcdec_bc3(blocks + b * 16, px.data(), 16);
            for (int p = 0; p < 16; ++p) count(px[p * 4 + 3]);
        }
    } else {
        return false;
    }
    if (!visible) return false;
    share = double(passing) / double(visible);
    return true;
}

bool convertMaterialWithDb(const std::shared_ptr<Database>& db, std::string_view requested,
                           const MaterialOptions& options, Material& material, std::string& error) {
    const std::string name = cleanAssetName(requested, true);
    if (!validAssetName(name)) { error = "invalid material path"; return false; }
    if (name == "tools/toolsskybox" || name.find("tools/sky") == 0) {
        error = "sky compile tool material is not emitted as a VMT; use the map sky setting";
        return false;
    }
    // Map-pack materials that the rpaks do not carry and that R1 cannot draw as authored. The R2 VMT of the
    // arena border dome (kodai_fake_screen_01_world: mp_coliseum, mp_coliseum_column, lf_deck, lf_meadow) and of the
    // skies/boomtowncubemap_* domes (grave, complex3, lf_deck, lf_uma) is an UnlitTwoTexture whose $texture2 is a
    // cube map. R1's UnlitTwoTexture binds $texture2 as a 2D texture, so the sky layer comes out empty and only the
    // scan-line layer remains (on mp_grave it showed as the pink checker). On the current provider build an UnlitGeneric
    // $envmap of env_cubemap (or the raw sky cube) blows the whole dome out to flat white and $envmaptint has no
    // effect, and $translucent/$additive scan-lines are invisible, so the closest safe look is the scan-line layer
    // alone in R2's layer colour (0.3 0.6 1.0). The scan-line texture is a plain VTF that the map-pack provider serves.
    // Shader track (default on, env R2TEX_SHADERS=0 turns it off; needs the engine's r2port shader override, engine/r2port/shaders/
    // r2_shader_override.cpp): the three materials keep the R2 UnlitTwoTexture VMT (layer colours, $addlayers and the
    // fresnel terms are R1 parameters too) and add `$godrayMinFadeDist 7701`, the opt-in marker for the engine's pixel
    // shader override `r2_ut_dome`, which samples `$texture2` as a cube map along the view direction. `$nofog 1` is
    // required by the override. R1 clamps $fresnelsharpness to 0..1, so R2's sharpness 5 becomes 1.
    // The override opts in only when the engine hook is present; without it the marker is inert and the cube is bound
    // as an unused 2D texture.
    // models/kodai/kodai_fake_screen_alpha (map-pack material of the mp_lf_* fake-sky shell models, converted models rename it
    // r2m/models/kodai/...): the rpaks do not carry it, so it came out as the R1 error texture, drawn as a thin pink/grey seam
    // line along every cell edge of the glass dome (mp_lf_meadow, stacks, deck, uma ...). R2 draws these seams as a black
    // additive layer (layer 1 colour 0.1 over $texture2 effects\black), i.e. nothing visible.
    if (name == "models/kodai/kodai_fake_screen_alpha") {
        material = Material{};
        material.name = name;
        material.vmt =
            "\"UnlitGeneric\"\n{\n"
            "\t\"$surfaceprop\" \"glass\"\n"
            "\t\"$basetexture\" \"effects\\black\"\n"
            "\t\"$additive\" \"1\"\n"
            "}\n";
        return true;
    }
    // models/mendoko/interior/mendoko_ui_decals/mendoko_ui_decals_01 (the 26 door hand scanners and the monitor-UI cards of
    // mp_forwardbase_kodai) and models/domestic/luggage_01_screen (models/angel_city/keypad_01): map-pack materials that
    // the rpaks do not carry, renamed r2m/ by the model converter, so the provider never found them and R1 drew its
    // magenta error pattern on the screens. R2's VMT is an UnlitTwoTexture (scan-line $basetexture scrolled under the UI
    // atlas in $texture2, $translucent + $screenblend, layer colour 0.1 0.3 1.5). R1's UnlitTwoTexture screenblend is
    // not reliable, so draw the UI atlas itself additively: cyan icons/text over the dark screen, like R2. The atlas VTF is
    // a plain map-pack file that the map-pack provider serves.
    if (name == "models/mendoko/interior/mendoko_ui_decals/mendoko_ui_decals_01" ||
        name == "models/domestic/luggage_01_screen") {
        material = Material{};
        material.name = name;
        const char* tex = name == "models/domestic/luggage_01_screen" ? "models\\domestic\\luggage_01_screen_col"
            : "models\\mendoko\\interior\\mendoko_ui_decals\\mendoko_ui_decals_col";
        material.vmt =
            "\"UnlitGeneric\"\n{\n"
            "\t\"$surfaceprop\" \"glass\"\n"
            "\t\"$basetexture\" \"" + std::string(tex) + "\"\n"
            "\t\"$additive\" \"1\"\n"
            "}\n";
        return true;
    }
    if (name == "world/test/kodai_fake_screen_01_world" || name == "skies/boomtowncubemap_grave" ||
        name == "skies/boomtowncubemap_desert") {
        material = Material{};
        material.name = name;
        const char* shadersEnv = std::getenv("R2TEX_SHADERS");   // default on; "0" restores the scan-line-only stand-in
        if (!(shadersEnv && shadersEnv[0] == '0')) {
            const char* cube = name == "world/test/kodai_fake_screen_01_world" ? "skies\\skycube"
                : name == "skies/boomtowncubemap_grave" ? "skies\\graveCubemap_" : "skies\\boomtownCubemap_desert_";
            material.vmt =
                "\"UnlitTwoTexture\"\n{\n"
                "\t\"$surfaceprop\" \"metal\"\n"
                "\t\"$basetexture\" \"effects\\dev_scanline_small_mip\"\n"
                "\t\"$texture2\" \"" + std::string(cube) + "\"\n"
                "\t\"$layercolor1\" \"[0.3 0.6 1.0]\"\n\t\"$layeralpha1\" \"0.9\"\n"
                "\t\"$layercolor2\" \"[2.2 2.2 2.2]\"\n"
                "\t\"$addlayers\" \"1\"\n"
                "\t\"$fresnel\" \"1\"\n"
                "\t\"$fresnelsharpness1\" \"0.3\"\n\t\"$fresnelouterstrength1\" \"0.25\"\n\t\"$fresnelinnerstrength1\" \"2.0\"\n"
                "\t\"$fresnelsharpness2\" \"1.0\"\n\t\"$fresnelouterstrength2\" \"1.0\"\n\t\"$fresnelinnerstrength2\" \"0.0\"\n"
                "\t\"$nofog\" \"1\"\n"
                "\t\"$godrayMinFadeDist\" \"7701\"\n"
                "}\n";
            return true;
        }
        material.vmt =
            "\"UnlitGeneric\"\n{\n"
            "\t\"$basetexture\" \"effects\\dev_scanline_small_mip\"\n"
            "\t\"$color\" \"[0.3 0.6 1.0]\"\n"
            "}\n";
        return true;
    }
    const char* variants[] = {"wld", "fix", "skn", "gen"};
    const AssetRecord* record = nullptr;
    const char* variant = nullptr;
    for (const char* candidate : variants) {
        const auto guid = materialGuid(name, candidate);
        record = findRecord(*db, guid, kMatl);
        if (record) { variant = candidate; break; }
    }
    if (!record) { error = "unresolved material " + name; return false; }
    auto family = db->getFamily(db->paks[record->pakIndex].family, error);
    if (!family) return false;
    std::vector<std::uint8_t> header;
    if (!readAssetHeader(*db, *record, family, header, error)) return false;
    if (header.size() < 0xd0) { error = "short matl header"; return false; }
    const PakData* materialOwner = findPakOwner(*family, record->pakIndex);
    if (!materialOwner) { error = "material pak is unavailable"; return false; }

    std::string shaderSet;
    const std::uint64_t shaderGuid = u64(header.data() + 0x90);
    if (const auto* shader = findRecord(*db, shaderGuid, kShds)) shaderSet = lowerAscii(shader->name);
    std::string surface;
    PagePtr surfacePtr{};
    std::memcpy(&surfacePtr, header.data() + 0x20, sizeof(surfacePtr));
    readCString(*family, *materialOwner, surfacePtr, surface);
    surface = lowerAscii(surface);

    PagePtr textureBegin{}, textureEnd{};
    std::memcpy(&textureBegin, header.data() + 0x98, sizeof(textureBegin));
    std::memcpy(&textureEnd, header.data() + 0xa0, sizeof(textureEnd));
    std::vector<std::uint64_t> slotGuids;
    if (textureBegin.index == textureEnd.index && textureEnd.offset >= textureBegin.offset &&
        ((textureEnd.offset - textureBegin.offset) % 8u) == 0) {
        const std::uint32_t slots = (textureEnd.offset - textureBegin.offset) / 8u;
        if (slots <= 64) {
            std::vector<std::uint8_t> table;
            if (readPageRange(*family, *materialOwner, textureBegin, static_cast<std::size_t>(slots) * 8, table, error)) {
                slotGuids.resize(slots);
                if (!table.empty()) std::memcpy(slotGuids.data(), table.data(), table.size());
            }
        }
    }
    auto texName = [&](std::size_t slot) -> std::string {
        if (slot >= slotGuids.size() || !slotGuids[slot]) return {};
        const AssetRecord* texture = findRecord(*db, slotGuids[slot], kTxtr);
        if (!texture) return {};
        std::string name = cleanAssetName(texture->name, true);
        return validAssetName(name) ? name : std::string();
    };
    std::map<std::size_t, std::string> usedSlots;
    auto use = [&](std::size_t slot) {
        const std::string tex = texName(slot);
        if (tex.empty()) return false;
        usedSlots.emplace(slot, tex);
        return true;
    };
    const bool tools = name.rfind("tools/", 0) == 0;
    const bool unlit = std::strcmp(variant, "gen") == 0 || shaderSet.find("unlit") != std::string::npos;
    const std::string shader = unlit ? "UnlitGeneric" :
        (std::strcmp(variant, "wld") == 0 ? "LightmappedGeneric" : "VertexLitGeneric");
    const bool lightmapped = shader == "LightmappedGeneric";
    const std::array<std::size_t, 4> layerSlots = {22, 23, 24, 26};
    const bool hasLayerSlots = lightmapped && std::any_of(layerSlots.begin(), layerSlots.end(),
        [&](std::size_t slot) { return slot < slotGuids.size() && slotGuids[slot] != 0; });
    const bool layersOff = hasLayerSlots && options.layerMode == LayerMode::layersOff;
    // Puddle terrain (default OFF, R2TEX_PUDDLES=1). R2 layer 0 of the "..._puddles_..." ground materials is water-like: gloss 255 over
    // the whole 512 map (world/dirt/dirt_forest_water_puddles_01_gls), F0 40/255, albedo 54 50 43, so R2 draws a dark mirror with the
    // trees reflected (mp_crashsite3 -4506.03 1288.21 1175.09 ang 36.44 81.19). R1 got a flat matte brown that is 2x brighter. With R1's
    // Fresnel environment terms on (the stock water VMTs use them), a x9 environment tint (the spec map is only 40/255) and a cool
    // dark $color the same spot turns dark blue-grey like R2 (maps\csl\NOTES.md, frame fd_f4_patch_floor.jpg). Tested on that one material only.
    const bool puddleLayers = hasLayerSlots && name.find("puddle") != std::string::npos && []() {
        const char* e = std::getenv("R2TEX_PUDDLES");
        return e && e[0] == '1';
    }();
    // `current` (the default) expands the single-channel R2 layer mask (slot 22, BC4 red only) to R=G=mask: R1's
    // $blendModulateTexture reads red AND green. `redOnly` keeps the old unexpanded mapping.
    const LayerMode effMode = options.layerMode == LayerMode::current ? LayerMode::maskRg : options.layerMode;
    material.usesLayers = hasLayerSlots;
    if (!tools) {
        use(0);
        // layers-off removes only the second layer (slots 22/23/24/26). The normal, specular, emissive and detail
        // slots must stay: a lightmapped material without $bumpmap runs a shader permutation that does not match
        // bumped lightmap data and shimmers in the sun/light shadow paths.
        use(1); use(3); use(4); use(12); use(13); use(14); use(15);
        if (lightmapped && !layersOff) {
            use(22); use(23); use(24); use(26);
        }
        if (usedSlots.find(0) == usedSlots.end()) { error = "material has no resolvable base texture: " + name; return false; }
        // Layer polarity. R2 blends layered brush materials with the vertex alpha as the weight of layer 2 (slots 23/24/26);
        // R1's $blendModulateTexture / $baseTexture2 blend has the opposite polarity (lightbaker inverts the alpha of every
        // layered mesh when going R1 -> R2, see lightref\FINDINGS.md section 6). bspdown cannot know which meshes are
        // layered, so the layers are exchanged here instead: base <-> base2, bump <-> bump2, spec <-> spec2. Verified on
        // mp_colony02 (grass over mud: R1 drew green ground where R2 has mud, and hard grass patch edges; with the swap the
        // ground, the road and the slope match R2). R2TEX_LAYER_SWAP=0 restores the old assignment.
        const char* swapEnv = std::getenv("R2TEX_LAYER_SWAP");
        if (hasLayerSlots && !layersOff && !(swapEnv && swapEnv[0] == '0') &&
            usedSlots.find(0) != usedSlots.end() && usedSlots.find(23) != usedSlots.end()) {
            const std::pair<std::size_t, std::size_t> layerPairs[] = {{0, 23}, {1, 24}, {3, 26}};
            for (const auto& pair : layerPairs) {
                std::string first, second;
                const auto a = usedSlots.find(pair.first);
                const bool haveFirst = a != usedSlots.end();
                if (haveFirst) { first = a->second; usedSlots.erase(a); }
                const auto b = usedSlots.find(pair.second);
                const bool haveSecond = b != usedSlots.end();
                if (haveSecond) { second = b->second; usedSlots.erase(b); }
                if (haveSecond) usedSlots[pair.first] = second;
                if (haveFirst) usedSlots[pair.second] = first;
                if (pair.second < slotGuids.size()) std::swap(slotGuids[pair.first], slotGuids[pair.second]);
            }
        }
    }

    // dxState[1] is the material draw state. R2 stores D3D blend factors minus one.
    const std::uint32_t blend = u32(header.data() + 0x70);
    const std::uint16_t depth = u16(header.data() + 0x70 + 0x14);
    const std::uint16_t raster = u16(header.data() + 0x70 + 0x16);
    // The matl CPU data is MaterialAssetCPU_t {PagePtr data; u32 size; u32}; the constant buffer is 224 bytes (14 float4)
    // on every shader set seen in the 20 maps. float4 #6 is the diffuse modulation: rgb tint, a opacity (glitch glass
    // 0.24 0.33 0.18 / 0.6, water_wild_02 1 1 1 / 0.75, ts_window01_dark tint 0.12 0.19 0.20). Opacity matters only
    // when the draw state blends.
    std::vector<float> constants;
    std::uint32_t constantsSize = 0;
    {
        std::vector<std::uint8_t> cpuHead, cpu; std::string cpuError;
        if (readPageRange(*family, *materialOwner, record->data, 16, cpuHead, cpuError)) {
            PagePtr cbPtr{};
            std::memcpy(&cbPtr, cpuHead.data(), sizeof(cbPtr));
            constantsSize = u32(cpuHead.data() + 8);
            if (constantsSize > 0x400) constantsSize = 0x400;
            if (readPageRange(*family, *materialOwner, cbPtr, constantsSize, cpu, cpuError)) {
                constants.resize(cpu.size() / 4u);
                if (!cpu.empty()) std::memcpy(constants.data(), cpu.data(), constants.size() * 4u);
            }
        }
    }
    if (std::getenv("R2TEX_MATERIAL_DEBUG")) {
        // One line per material: name|variant|shader set|surface|blend|depth|raster|cbuffer size|cbuffer floats.
        std::fprintf(stderr, "matcb|%s|%s|%s|%s|%08x|%04x|%04x|%u|", name.c_str(), variant, shaderSet.c_str(), surface.c_str(),
                     blend, depth, raster, constantsSize);
        for (std::size_t i = 0; i < constants.size(); ++i) std::fprintf(stderr, "%s%.5g", i ? "," : "", constants[i]);
        std::fprintf(stderr, "\n");
        for (std::size_t slot = 0; slot < slotGuids.size(); ++slot) {
            if (!slotGuids[slot]) continue;
            unsigned tw = 0, th = 0, tf = 0, tm = 0;
            if (const AssetRecord* tex = findRecord(*db, slotGuids[slot], kTxtr)) {
                std::vector<std::uint8_t> th_; std::string ignoredError;
                auto texFamily = db->getFamily(db->paks[tex->pakIndex].family, ignoredError);
                if (texFamily && readAssetHeader(*db, *tex, texFamily, th_, ignoredError) && th_.size() >= 0x38) {
                    tw = u16(th_.data() + 0x10); th = u16(th_.data() + 0x12); tf = u16(th_.data() + 0x16);
                    tm = th_[0x1d] + th_[0x21] + th_[0x22];
                }
            }
            std::fprintf(stderr, "matslot|%s|%zu|%s|%u|%u|%u|%u\n", name.c_str(), slot, texName(slot).c_str(), tw, th, tf, tm);
        }
    }
    double materialTint[3] = {1.0, 1.0, 1.0};
    double materialOpacity = 1.0;
    if (constants.size() >= 28) {
        const float* c06 = constants.data() + 24;
        bool sane = true;
        for (int i = 0; i < 4; ++i) sane = sane && std::isfinite(c06[i]) && c06[i] >= 0.0f && c06[i] <= 8.0f;
        if (sane) {
            for (int i = 0; i < 3; ++i) materialTint[i] = c06[i];
            materialOpacity = std::min(1.0f, c06[3]);
        }
    }
    const bool cut = shaderSet.find("cut") != std::string::npos;
    const bool blendEnabled = (blend & 0x2u) != 0;
    const std::uint32_t sourceBlend = ((blend >> 2u) & 0x1fu) + 1u;
    const std::uint32_t destinationBlend = ((blend >> 7u) & 0x1fu) + 1u;
    constexpr std::uint32_t kBlendOne = 2;
    constexpr std::uint32_t kBlendInvSrcAlpha = 6;
    const bool additive = blendEnabled && sourceBlend == kBlendOne && destinationBlend == kBlendOne;
    const bool premultipliedAlpha = blendEnabled &&
        sourceBlend == kBlendOne && destinationBlend == kBlendInvSrcAlpha;
    const bool translucent = !additive &&
        (shaderSet.find("trans") != std::string::npos || blendEnabled);
    const bool rasterDecalPreset = (raster & 0x70u) == 0x10u;
    const bool overlayDepthState = (depth & 0x17u) == 0x07u;
    const bool overlayProfile = premultipliedAlpha &&
        shaderSet.find("trans") != std::string::npos &&
        overlayDepthState && rasterDecalPreset;
    // Map this observed R2 surface-overlay profile to R1's $decal parameter. The raster decal preset (state 0x16) with
    // a no-depth-write state (0x07) is what every R2 world decal uses whatever its blend: premultiplied overlays and
    // also alpha-tested stencils (world/mcor/kodai_ind_decals_01, beacon_signage_03, *_caution_stripe_decals) and
    // opaque vertex-colour overlays (beacon_tileable_decal_01). Without $decal those lay coplanar with the wall and
    // z-fought it (mp_forwardbase_kodai "03 DOCK" stencil: orange fill lost in horizontal streaks).
    const bool rasterDecal = lightmapped && !tools && overlayDepthState && rasterDecalPreset;
    const bool decal = name.find("/decal/") != std::string::npos ||
        shaderSet.find("decal") != std::string::npos || overlayProfile || rasterDecal;
    // Glass is a draw state, not a name: R2 materials named *glass* or with the glass surface property whose draw state is opaque
    // (ts_window01_opaque, glass_striped_01, glass_thick_unbreakable_03, 59 materials over the 20 maps) are solid in R2. Marking them
    // translucent made R1 read their non-opacity albedo alpha (ts_window01_col alpha 0.58) as transparency over the empty room
    // behind (mp_black_water_canal "SERVICE ENTRANCE" window drew as a flat pale-blue pane).
    const bool glass = (name.find("glass") != std::string::npos || surface == "glass") && (translucent || additive);
    // mp_homestead river (static prop homestead_waterfall_01_sort: body world/homestead/homestead_water_01 + foam
    // world/homestead/homestead_water_whtwsh_01_btt; user poses eye 2277.81 -889.36 15.34 and 3243.92 -1580.03 -32.66). The converted body was a
    // flat 0.85 near-black sheet (R2 opacity 0.85 premultiplied over a depth-faded water shader) with a hard outline and no reflection, between
    // two bands of full-strength white foam: a black patch on the river. R2 draws dark slate water through which the pebbled bed shows, with
    // ripple reflections and faint foam. R1 cannot do the R2 shore fade: static props ignore the model's per-vertex alpha ($vertexalpha with
    // or without $vertexcolor/$vertcoloristint gave pixel-identical frames, the body mesh carries alpha 255 inside and 0 at the shore), so the
    // soft edge is approximated with a lower flat alpha instead. Measured in game (tier0 581B45E9, 1280x720, same two poses, water boxes against R2
    // mean luminance / texture std): pose 2 R2 69.1 / 17.5, before 65.0 / 19.2 (hard curved edge), now 74.9 / 16.1; pose 1 R2 70.3, before 67.0 (black
    // patch), now 60.9. R2TEX_HS_WATER=0 returns the old output.
    const bool hsWater = !tools && !unlit && !lightmapped && surface == "water" && translucent && !additive &&
        name.rfind("world/homestead/", 0) == 0 && !(std::getenv("R2TEX_HS_WATER") && std::atoi(std::getenv("R2TEX_HS_WATER")) == 0);
    const bool hsWaterFoam = hsWater && shaderSet.find("lyrtrans") != std::string::npos;
    const bool hsWaterBody = hsWater && !hsWaterFoam;

    // R2 world/atmosphere sheets (godray_*, atmosphere_*) fade by distance to the camera (shader token Adf), so cards
    // vanish as the viewer approaches. R1's own godray materials use the Basic shader with $godray and
    // $godrayMinFadeDist/$godrayMaxFadeDist for exactly this; emit that class for them. The max distance is the number
    // in the R2 name (godray_500_fade: 30..500), like R1's stock godray_250_fade / godray_500_fade.
    const bool atmosphereSheet = !tools && unlit && additive && name.rfind("world/atmosphere/", 0) == 0 &&
        shaderSet.find("vcola") != std::string::npos;
    const char* godrayModeEnv = std::getenv("R2TEX_GODRAY_MODE");
    const std::string godrayMode = godrayModeEnv ? godrayModeEnv : "basic";
    const bool godray = atmosphereSheet && shaderSet.find("adf") != std::string::npos && godrayMode.rfind("basic", 0) == 0;
    int godrayMax = 500;
    if (godray) {
        const std::size_t us = name.find('_', name.rfind('/') + 1);
        if (us != std::string::npos) godrayMax = std::max(60, std::atoi(name.c_str() + us + 1));
    }
    // Translucent (not additive) atmosphere cloud sheets with the alpha distance fade (Adf/Aef; mp_forwardbase_kodai beacon_clouds): R2 fades
    // them against scene depth, so in the open sky they are all but invisible; R1 has no such fade and draws them at full vertex alpha, which showed
    // as an orange dust wall behind the cliffs and a fan of hard orange rays across the whole sky (mp_forwardbase_kodai, R2 frames show none of it).
    // The Kodai cloud sheet matched R2 only at alpha 0: 0.3 still leaves the orange ray fan. Keep the small general
    // reduction for other ADF sheets, but remove this sheet's R1-only open-sky contribution by default.
    // R2TEX_SOFT_CLOUD_ALPHA is an explicit calibration override for either case.
    const bool softCloudSheet = !tools && unlit && translucent && !additive && name.rfind("world/atmosphere/", 0) == 0 &&
        shaderSet.find("adf") != std::string::npos;
    double softCloudAlpha = name == "world/atmosphere/beacon_clouds" ? 0.0 : 0.05;
    if (const char* e = std::getenv("R2TEX_SOFT_CLOUD_ALPHA")) softCloudAlpha = std::clamp(std::atof(e), 0.0, 1.0);
    // The kodai 3D sky model (models/vistas/kodai_sky.mdl) carries a ring of "lower clouds" (models/vistas/beacon/beacon_se_k, panorama
    // kodai_se_lower_clouds_col, vertex alpha 0..255, the ring is open at the map centre) that R1 draws as a hard-edged flat cloud sheet:
    // seen from the map border and outside (noclip positions around x 3000..9300), it cuts through the scene and hides the rocks below,
    // at (8617 644 1522) it fills the lower half of the frame. R2 draws nothing of it at those viewpoints (navy gap and soft cloud banks
    // from the other sky layers; R2 frames at 7 poses, maps/kodai/cloudwall/shots), R1 with alpha 0 matches those frames, and the 7 in-map
    // poses change by at most MAD 4/255 (animation). beacon_se_k has the same shader set, blend and depth state as the sky layers
    // beacon_se_a/b that do match, so the R2 reason is not in the material. Same treatment as world/atmosphere/beacon_clouds.
    // R2TEX_KODAI_LOWER_CLOUDS=1 keeps the sheet.
    const bool kodaiLowerCloudRing = name == "models/vistas/beacon/beacon_se_k" && !(std::getenv("R2TEX_KODAI_LOWER_CLOUDS") &&
                                                                                    std::atoi(std::getenv("R2TEX_KODAI_LOWER_CLOUDS")) != 0);
    // Flat-textured sheets: bake the texture mean into constants (see flatSheetStats).
    FlatSheet flatSheet;
    if (atmosphereSheet && (!godray || godrayMode == "basic_flat")) {
        const auto slot0 = usedSlots.find(0);
        if (slot0 != usedSlots.end() && slotGuids[0])
            if (const AssetRecord* texture = findRecord(*db, slotGuids[0], kTxtr))
                flatSheet = flatSheetStats(db, *texture);
    }
    // Pure emitters on world brushes: black albedo, an all-white emissive mask (_ilm) and an emissive tint (float4 #10, HDR). R2 draws
    // albedo * light + _ilm * tint, so such a strip glows in the tint colour. R1's LightmappedGeneric has no emissive input the
    // converter can feed (shaderlab\CHANNELS.md 2.6), so the strip came out solid black (mp_glitch vr_light_trim_01_totrans: the
    // frame around the ramp wall panel was a black band, R2 shows a warm glowing trim; the only material of the 20 maps that is a
    // pure emitter). Such a material becomes UnlitGeneric: the white _ilm texture times $color = the tint. Masked emitters (signs,
    // LED floors with a real albedo) are not covered by this path.
    // The R2 tint is HDR (mp_glitch 3.0 2.53 2.11). R1 draws an unlit surface about 1.7 times brighter on screen than R2 tone-maps the same
    // emissive: the strip is dim warm grey in R2 (display luminance median 94, p90 111, p99 166 over the glow pixels of the user's
    // frame) and blown white at tint 3.0 in R1. Measured in game on the same pose, mean display luminance of the strip against the scale
    // (tint 3.0 2.53 2.11 times k): k 0.4 -> 191, 0.25 -> 106, 0.2 -> 78, 0.15 -> 56. k 0.25 (106) matches R2's median (94) to p90 (111) over the glow pixels (R2 fades the glow across the strip with the layer weight from the vertex alpha; R1 draws it uniform).
    constexpr double kPureEmitterTintCap = 4.0;
    constexpr double kPureEmitterScale = 0.25;
    // Layered pure emitters (mp_glitch vr_light_trim_01_totrans: float4 #10 3.0 2.53 2.11, layer slot 22 present) are not drawn flat in R2:
    // the shader set is a premultiplied blend (ONE / INV_SRC_ALPHA) whose weight c comes from the mesh vertex alpha a, out = E * c + dst * (1 - c)
    // (measured against the R2 frame at the mp_glitch ramp panel: with c = 0.65 at the vertex alpha 89 edge, E = display 177 149 121 and
    // dst = panel 23 55 90 give the observed glow pixel 123 116 110 on all three channels). The glow is brightest at the outer edge of the 32
    // unit strip and gone about half way in (c = clamp((160 - a) / 109, 0, 1): a 89 -> 0.65, 0 -> 1, 127 -> 0.3, >= 160 -> 0).
    // The VMT is UnlitGeneric $translucent 1 of a generated ramp texture (buildGlowRampVtf, name r2tex/glow/<_ilm name>; RGB white, alpha = c at
    // the texel a) times $color = E; bspdown rule 24 (vcalpha.cpp, kEmitterGlowMaterials) writes each vertex's alpha as its texture coordinate
    // u = (a + 0.5) / 256, so the interpolated coordinate reproduces R2's per-pixel clamp of the interpolated alpha (a plain $vertexalpha ramp
    // between the two vertex rows cannot clip: the glow then spread over the whole strip like a veil). Without the rule the coordinates are the
    // R2 tiling and the glow is wrong, so the name list there must stay in sync with this predicate (only
    // world/vr_training/vr_light_trim_01_totrans over the 20 maps).
    // $color is calibrated on the R1 frame against R2 (display 109 104 100 against R2 96 94 99 at the same pixel row of the panel strip, profile
    // of the glow band 470..498 within 15 of R2 on all channels): the HDR tint compressed as 0.585 * tint^0.45 (0.959 0.887 0.818 for 3.0 2.53 2.11).
    // R2TEX_EMITTER_GLOW=0 keeps the flat opaque strip.
    constexpr double kPureEmitterGlowGain = 0.585;
    constexpr double kPureEmitterGlowExponent = 0.45;
    if (!tools && lightmapped && !additive && !cut && usedSlots.find(0) != usedSlots.end() &&
        usedSlots.find(4) != usedSlots.end() && slotGuids.size() > 4 && slotGuids[0] && slotGuids[4] && constants.size() >= 43) {
        double emitTint[3];
        for (int i = 0; i < 3; ++i) emitTint[i] = std::isfinite(constants[40 + i]) ? std::clamp<double>(constants[40 + i], 0.0, kPureEmitterTintCap) : 0.0;
        if (emitTint[0] + emitTint[1] + emitTint[2] > 0.004) {
            const AssetRecord* albedoRecord = findRecord(*db, slotGuids[0], kTxtr);
            const AssetRecord* maskRecord = findRecord(*db, slotGuids[4], kTxtr);
            std::vector<std::uint8_t> albedoVtf, maskVtf;
            std::string textureWhy;
            double albedoMean[3] = {255, 255, 255}, maskMean[3] = {0, 0, 0};
            if (albedoRecord && maskRecord && slotGuids[0] != slotGuids[4] &&
                convertTextureWithDb(db, *albedoRecord, TextureOptions{}, albedoVtf, textureWhy) &&
                vtfSmallestMipMean(albedoVtf, albedoMean) && *std::max_element(albedoMean, albedoMean + 3) < 6.0 &&
                convertTextureWithDb(db, *maskRecord, TextureOptions{}, maskVtf, textureWhy) &&
                vtfSmallestMipMean(maskVtf, maskMean) && *std::min_element(maskMean, maskMean + 3) >= 240.0) {
                std::ostringstream pure;
                pure << "\"UnlitGeneric\"\n{\n";
                addVmtParam(pure, "$surfaceprop", surfaceKnown(surface) ? surface : "default");
                const char* glowEnv = std::getenv("R2TEX_EMITTER_GLOW");
                const bool glow = hasLayerSlots && translucent && !(glowEnv && std::atoi(glowEnv) == 0);
                addVmtParam(pure, "$basetexture", vmtTextureName(glow ? glowRampName(usedSlots[4]) : usedSlots[4]));
                char colorText[64];
                if (glow) {
                    std::snprintf(colorText, sizeof(colorText), "[%.4f %.4f %.4f]", kPureEmitterGlowGain * std::pow(emitTint[0], kPureEmitterGlowExponent),
                                  kPureEmitterGlowGain * std::pow(emitTint[1], kPureEmitterGlowExponent),
                                  kPureEmitterGlowGain * std::pow(emitTint[2], kPureEmitterGlowExponent));
                } else {
                    std::snprintf(colorText, sizeof(colorText), "[%.4f %.4f %.4f]", emitTint[0] * kPureEmitterScale, emitTint[1] * kPureEmitterScale,
                                  emitTint[2] * kPureEmitterScale);
                }
                addVmtParam(pure, "$color", colorText);
                if (glow) addVmtParam(pure, "$translucent", "1");
                // R2 draws the strip with the decal raster state and no depth write over the coplanar wall panel; without $decal R1 z-fights
                // the two (dotted dither pattern across the strip in game).
                if (decal) addVmtParam(pure, "$decal", "1");
                pure << "}\n";
                material.name = name;
                material.vmt = pure.str();
                material.textures.clear();
                material.usesLayers = false;
                TextureRef texture;
                texture.guid = slotGuids[4];
                texture.slot = 4;
                if (glow) {
                    texture.name = glowRampName(usedSlots[4]);
                    texture.transform = TextureTransform::glowRamp;
                } else {
                    texture.name = usedSlots[4];
                }
                material.textures.push_back(std::move(texture));
                return true;
            }
        }
    }
    // Screen emitters on world brushes: sign faces and LED floors whose emissive mask (_ilm) covers much of the surface (mean luminance
    // at least 40/255) with a real albedo. R2 adds _ilm * tint (float4 #10) to the lit albedo, so such a face is dominated by its own picture;
    // R1's LightmappedGeneric cannot take an emissive input, so these faces drew as lit albedo only (mp_eden sign_billboard_01, sign_fembot,
    // eden_ts_screen_03, mp_complex3 floor_tile_led_01, mp_colony02/mp_relic02 floor_lightstrip: dim, no glow). The face becomes UnlitGeneric
    // of the _ilm texture (the albedo texture itself when R2 uses the same guid for both slots) times $color = tint (HDR part compressed, kScreenHdrKnee).
    // Sparse masks (s2s_roof_light_01 and s2s_stairs_01 lamps, decals_embers_01 veins, ilm mean 2..10) are left alone: an unlit face would
    // lose the lit surface around the lamps, and R1 has no second pass for a world mesh.
    // Measured in game at mp_eden (eye 70 units from each quad, R2 frames at the same pose): tint 1 faces (sign_billboard_01, sign_fembot)
    // match R2 at $color = tint (k 1.0; k 0.5 reads dim, k 0.25 dark). A tint above 1 is HDR and R1's unlit surface clips, so the part above
    // 1 counts a quarter (eden_ts_screen_03, tint 0.91 2.40 2.52: k 1.0 bloomed to a blown cyan, k 0.5 was already saturated).
    constexpr double kScreenHdrKnee = 0.25;
    constexpr double kScreenMinMaskLuminance = 40.0;
    if (!tools && lightmapped && !additive && !cut && name.rfind("world/", 0) == 0 && shaderSet.find("emit") != std::string::npos &&
        usedSlots.find(4) != usedSlots.end() && slotGuids.size() > 4 && slotGuids[4] && constants.size() >= 43) {
        double emitTint[3];
        for (int i = 0; i < 3; ++i) emitTint[i] = std::isfinite(constants[40 + i]) ? std::clamp<double>(constants[40 + i], 0.0, kPureEmitterTintCap) : 0.0;
        if (emitTint[0] + emitTint[1] + emitTint[2] > 0.004) {
            const AssetRecord* maskRecord = findRecord(*db, slotGuids[4], kTxtr);
            std::vector<std::uint8_t> maskVtf;
            std::string textureWhy;
            double maskMean[3] = {0, 0, 0};
            if (maskRecord && convertTextureWithDb(db, *maskRecord, TextureOptions{}, maskVtf, textureWhy) &&
                vtfTopMipMean(maskVtf, maskMean) &&
                0.2126 * maskMean[0] + 0.7152 * maskMean[1] + 0.0722 * maskMean[2] >= kScreenMinMaskLuminance) {
                std::ostringstream screen;
                screen << "\"UnlitGeneric\"\n{\n";
                addVmtParam(screen, "$surfaceprop", surfaceKnown(surface) ? surface : "default");
                addVmtParam(screen, "$basetexture", vmtTextureName(usedSlots[4]));
                double color[3];
                for (int i = 0; i < 3; ++i) color[i] = std::min(emitTint[i], 1.0) + kScreenHdrKnee * std::max(emitTint[i] - 1.0, 0.0);
                char colorText[64];
                std::snprintf(colorText, sizeof(colorText), "[%.4f %.4f %.4f]", color[0], color[1], color[2]);
                addVmtParam(screen, "$color", colorText);
                if (decal) addVmtParam(screen, "$decal", "1");
                screen << "}\n";
                material.name = name;
                material.vmt = screen.str();
                material.textures.clear();
                material.usesLayers = false;
                TextureRef texture;
                texture.guid = slotGuids[4];
                texture.name = usedSlots[4];
                texture.slot = 4;
                material.textures.push_back(std::move(texture));
                return true;
            }
        }
    }
    const bool vertexLit = shader == "VertexLitGeneric";
    std::ostringstream out;
    std::set<std::size_t> referencedSlots;
    out << '\"' << (godray ? "Basic" : shader.c_str()) << "\"\n{\n";
    if (godray) {
        addVmtParam(out, "$vertcoloristint", "1");
        addVmtParam(out, "$nodecal", "1");
        addVmtParam(out, "$godray", "1");
        addVmtParam(out, "$godrayMinFadeDist", "30");
        addVmtParam(out, "$godrayMaxFadeDist", std::to_string(godrayMax));
    }
    const std::string safeSurface = surfaceKnown(surface) ? surface : "default";
    addVmtParam(out, "$surfaceprop", safeSurface);
    // R1 reads $vertexalpha as the opacity of the prop: the opaque R2 model materials that carry vertex alpha (shader set "Vcola" without
    // "Vcolt"; the fir trunk models/foliage/tree_fir_large_01 of mp_black_water_canal) draw pale, shimmering and partly missing with it
    // (round 16 user report; load-time A/B on the trunk: `$vertexalpha 1` alone reproduces it, bump map and envmap do not). R2 does not use
    // that alpha as opacity there, so a model material that is not translucent, additive, glass or cut keeps no $vertexalpha and is
    // treated as opaque (albedo alpha aliased to 255 like every other opaque material).
    const bool modelSurface = vertexLit || options.forModel;
    const bool opaqueKind = !tools && !additive && !translucent && !glass && !cut;
    const bool dropVertexAlpha = modelSurface && opaqueKind;
    const bool opaqueAlbedo = opaqueKind && (dropVertexAlpha || shaderSet.find("vcola") == std::string::npos);
    // Pure metals: R2 stores a black albedo and puts the metal colour in the specular F0 map (sRGB 116..150). R1's stock
    // LightmappedGeneric draws no usable specular term (shaderlab\CHANNELS.md 2.2), so the surface came out solid black
    // (mp_black_water_canal diamond plate floor world/metal/metal_diamond_plate_circles01, R2 shows grey steel; the only one of
    // the 2,795 materials of the 20 maps with an albedo below 6/255 and a specular above 90/255). Such a material takes its
    // F0 map as albedo, scaled by kMetalAlbedoScale (0.3: sRGB 150 -> linear albedo about 0.09, a dark steel).
    constexpr double kMetalAlbedoScale = 0.3;
    bool metalFromSpec = false;
    if (!tools && !additive && !translucent && !cut && !unlit && surface.rfind("metal", 0) == 0 &&
        slotGuids.size() > 3 && slotGuids[0] && slotGuids[3] && usedSlots.find(0) != usedSlots.end() &&
        usedSlots.find(3) != usedSlots.end() && usedSlots.find(23) == usedSlots.end()) {
        const AssetRecord* albedoRecord = findRecord(*db, slotGuids[0], kTxtr);
        const AssetRecord* specRecord = findRecord(*db, slotGuids[3], kTxtr);
        std::vector<std::uint8_t> albedoVtf, specVtf;
        std::string textureWhy;
        double albedoMean[3] = {255, 255, 255}, specMean[3] = {0, 0, 0};
        if (albedoRecord && specRecord &&
            convertTextureWithDb(db, *albedoRecord, TextureOptions{}, albedoVtf, textureWhy) &&
            vtfSmallestMipMean(albedoVtf, albedoMean) &&
            *std::max_element(albedoMean, albedoMean + 3) < 6.0 &&
            convertTextureWithDb(db, *specRecord, TextureOptions{}, specVtf, textureWhy) &&
            vtfSmallestMipMean(specVtf, specMean) &&
            (specMean[0] + specMean[1] + specMean[2]) / 3.0 > 90.0) {
            metalFromSpec = true;
            usedSlots[0] = usedSlots[3];
            slotGuids[0] = slotGuids[3];
        }
    }
    // Dark opaque glass panes (world/timeshift/windows/ts_window01_opaque on mp_black_water_canal, complex3, kodai, grave and
    // ts_window01_wet_opaque on complex3: opaque draw state, glass surface, diffuse tint 0.122 0.188 0.204 over a flat sRGB 100 albedo).
    // R2 draws the mp_black_water_canal "SERVICE ENTRANCE" window as a dark teal grey (display luminance 43.5, mean RGB 36 45 49 at the
    // user's pose); R1 drew it near black (luminance 18 there, 29 and 12 at two nearby poses). Measured in game (tier0 581B45E9, loose VMTs,
    // 1280x720, pane box mean luminance): the sort has its patch material (cubemap 1), so the env term is bound; with it removed the
    // pane is 27 / 10 (u0 / p7), $envmaptint 0.5 gives 29 / 12 and the pre round 9 value 1.0 only 33 / 17: halving the env term is
    // not the cause. $color x 3 gives 61 / 58 and x 2.2 about 46 / 37: the deficit is in the diffuse term (R1's lightmap light on
    // this shaded pane is a quarter to a third of R2's). The tint is therefore lifted by darkGlassGain and desaturated 45 % toward its
    // luminance (R2's pane is greyer than its tint, R/G 0.80 against 0.65, because the neutral sky reflection adds to the diffuse).
    // Result at the user's pose 39.3 (RGB 34 41 44), 44.5 and 35.3 at the other two (R2 43.5, 36 45 49; 35.5 at the third).
    // The same material on the sunlit mp_complex3 facade was already at R2's level (34 against 33.6) and goes to 50: the one trade-off
    // of a per-material constant. Only opaque glass whose tint is dark (max < 0.5) is touched (2 materials over the 20 maps);
    // R2TEX_GLASS_GAIN overrides the gain (1 = the previous output byte for byte).
    double darkGlassGain = 2.2;
    if (const char* e = std::getenv("R2TEX_GLASS_GAIN")) darkGlassGain = std::clamp(std::atof(e), 0.0, 8.0);
    const bool darkGlassPane = !tools && lightmapped && !unlit && !vertexLit && !options.forModel && surface == "glass" &&
        !translucent && !additive && !cut &&
        std::max({materialTint[0], materialTint[1], materialTint[2]}) < 0.5 && darkGlassGain != 1.0;
    // Opacity-map ("Opam") sets: the opacity map in slot 13 is merged into the albedo alpha (see mergeOpacityVtf).
    const bool opacityMap = !tools && shaderSet.find("opam") != std::string::npos &&
        (translucent || additive || cut) && usedSlots.find(0) != usedSlots.end() &&
        usedSlots.find(13) != usedSlots.end() && slotGuids[0] && slotGuids[13];
    // Foliage cavity bake (see buildFoliageVtf): alpha-tested vertex-lit materials with a Cav set, a cavity map and no
    // baked vertex colour (R2TEX_FOLIAGE_CAV=0 turns the bake off; the exponent is the same variable).
    const char* foliageEnv = std::getenv("R2TEX_FOLIAGE_CAV");
    const bool foliageCavity = !tools && cut && shader == "VertexLitGeneric" && shaderSet.find("cav") != std::string::npos &&
        shaderSet.find("vcolt") == std::string::npos && !(foliageEnv && std::atof(foliageEnv) == 0.0) &&
        usedSlots.find(0) != usedSlots.end() && usedSlots.find(12) != usedSlots.end() &&
        slotGuids.size() > 12 && slotGuids[0] && slotGuids[12] && !slotGuids[11];   // an AO map (slot 11) means the set already has its own occlusion
    // Other alpha-tested grass/foliage cards without the cavity bake (grass_brown_long_01, grass_desert_01, grass_high_02, ground plants,
    // weeds ...): same reasoning, no $envmap. mp_lf_traffic: the cube reflection made the dry straw white-lavender (R2 golden); without it
    // the straw colour matches R2.
    const bool foliageNoEnv = foliageCavity || (!tools && cut && (shader == "VertexLitGeneric" || options.forModel) &&
        (surface == "grass" || name.find("foliage") != std::string::npos));
    const char* normalsEnv = std::getenv("R2TEX_NORMALS");   // default on; "0" passes the R2 BC5/slope texture through unchanged
    const bool normalRepack = !tools && !(normalsEnv && normalsEnv[0] == '0');
    // Uber carriers (MaterialOptions::uberPack, shaderlab/uber/DESIGN.md sec 9). Candidates are the materials the engine's
    // LightmappedGeneric override can take: world shader, bump and reflection tint present (the same slots that make the VMT carry
    // $bumpmap / $reflectiontint), no godray. AO (slot 11) / cavity (slot 12) then ride in a synthetic r2tex/pbr texture: single
    // layer as $detailColor + $detailColorMode 1 (not when R2 already supplies a detail colour in slot 14), two layers as the
    // $blendModulateTexture itself plus the $treesway 7701 marker the override keys on (stock reads only its R and G).
    bool uberCandidate = options.uberPack && !tools && lightmapped && !unlit && !options.forModel && !godray && !foliageNoEnv &&
        usedSlots.find(1) != usedSlots.end() && usedSlots.find(3) != usedSlots.end();
    if (uberCandidate) {
        // The bound detail/blend carrier has only the base UV. UV<n><digits>Samp assigns one UV set per occupied R2 slot
        // (the first digit is the number of sets); omit the carrier if AO/cavity or the layer mask needs another set.
        // In particular animated UV sets cannot be baked into one static texture. This excludes four world materials in the
        // 20-map census; their original VMT stays intact rather than applying occlusion at the wrong coordinates.
        const std::size_t samp = shaderSet.find("samp");
        std::size_t begin = samp;
        while (samp != std::string::npos && begin > 0 && std::isdigit(static_cast<unsigned char>(shaderSet[begin - 1]))) --begin;
        if (samp != std::string::npos && begin >= 2 && samp - begin >= 2 && shaderSet.compare(begin - 2, 2, "uv") == 0) {
            char baseUv = 0;
            std::size_t digit = begin + 1;
            for (std::size_t slot = 0; slot < slotGuids.size(); ++slot) {
                if (!slotGuids[slot]) continue;
                if (digit >= samp) { uberCandidate = false; break; }
                const char uv = shaderSet[digit++];
                if (slot == 0) baseUv = uv;
                if ((slot == 11 || slot == 12 || (hasLayerSlots && slot == 22)) && uv != baseUv)
                    uberCandidate = false;
            }
        }
    }
    const std::uint64_t uberAoGuid = uberCandidate && !texName(11).empty() ? slotGuids[11] : 0;
    const std::uint64_t uberCavityGuid = uberCandidate && !texName(12).empty() ? slotGuids[12] : 0;
    const bool uberHasMaps = uberAoGuid != 0 || uberCavityGuid != 0;
    const bool uberLayered = uberHasMaps && hasLayerSlots && !layersOff && effMode == LayerMode::maskRg &&
        usedSlots.find(22) != usedSlots.end() && usedSlots.find(23) != usedSlots.end() &&
        usedSlots.find(24) != usedSlots.end() && usedSlots.find(26) != usedSlots.end();
    const bool uberSingle = uberHasMaps && !hasLayerSlots && usedSlots.find(14) == usedSlots.end();
    bool glossBake = false, gloss2Bake = false;   // R2TEX_ENV=gloss (set below, read by the texture list)
    if (tools) {
        addVmtParam(out, "%compilenodraw", "1");
    } else {
        // Opaque materials must not see R2's non-opacity albedo alpha (see forceOpaqueVtf).
        if (opaqueAlbedo) {
            for (const std::size_t albedoSlot : {std::size_t(0), std::size_t(23)}) {
                auto albedo = usedSlots.find(albedoSlot);
                if (albedo != usedSlots.end()) albedo->second = opaqueAlbedoName(albedo->second);
            }
        }
        if (opacityMap || foliageCavity)
            usedSlots[0] = opacityMergeName(slotGuids[0], opacityMap ? slotGuids[13] : 0, foliageCavity ? slotGuids[12] : 0);
        // Slot 1 and 24 normal maps are re-encoded as R1 unit-normal DXT1 (see convertNormalVtf); R2TEX_NORMALS=0 keeps the raw R2 texture.
        if (normalRepack) {
            for (const std::size_t normalSlot : {std::size_t(1), std::size_t(24)}) {
                auto normal = usedSlots.find(normalSlot);
                if (normal != usedSlots.end()) normal->second = normalMapName(normal->second);
            }
        }
        auto param = [&](std::size_t slot, const char* key) {
            auto it = usedSlots.find(slot);
            if (it != usedSlots.end()) {
                addVmtParam(out, key, vmtTextureName(it->second));
                referencedSlots.insert(slot);
            }
        };
        if (!flatSheet.ok) param(0, "$basetexture");
        if (!unlit) param(1, "$bumpmap");
        // Env tokens (R2TEX_ENV; see EnvTokens): slot 3 with its gloss map becomes the DXT5 spec+gloss carrier (opt-in `gloss`).
        const EnvTokens& envTk = envTokens();
        const auto endsWith = [](const std::string& s, const char* suffix) {
            const std::size_t n = std::strlen(suffix);
            return s.size() >= n && s.compare(s.size() - n, n, suffix) == 0;
        };
        const bool envTokenSafe = !puddleLayers && !hsWaterBody;
        // gloss / blur are for world (lightmapped) materials only: models (VertexLitGeneric, r2m/) keep the plain spc texture.
        const bool worldEnv = lightmapped && !options.forModel && !vertexLit;
        glossBake = envTk.gloss && envTokenSafe && worldEnv && !unlit && !foliageNoEnv && slotGuids.size() > 3 && slotGuids[3] && slotGuids[2] &&
            usedSlots.find(3) != usedSlots.end() && endsWith(lowerAscii(texName(2)), "_gls");
        gloss2Bake = envTk.gloss && envTokenSafe && worldEnv && !unlit && !foliageNoEnv && slotGuids.size() > 26 && slotGuids[26] &&
            slotGuids[25] && usedSlots.find(26) != usedSlots.end() && endsWith(lowerAscii(texName(25)), "_gls");
        if (glossBake) usedSlots[3] = specGlossName(slotGuids[3], slotGuids[2]);
        if (gloss2Bake) usedSlots[26] = specGlossName(slotGuids[26], slotGuids[25]);
        // Foliage (cavity bake) emits no env reflection: R2 occludes foliage specular with the cavity map, R1 has no such term and
        // the cube reflection on up-facing cards is a pale blue sheen (homestead grass B/G 1.47x R2; hue 1.10x without it).
        if (!unlit && !foliageNoEnv && usedSlots.find(3) != usedSlots.end()) {
            param(3, "$reflectiontint");
            param(3, "$reflectiontintshininess");
            addVmtParam(out, "$reflectiontintcolor", "1");
            {
                // Model (VertexLitGeneric) materials over-reflect in R1 (prop brightness conv/R2 1.75 at mat_envmap_scale 2, LightVerify):
                // R2TEX_MODEL_ENVTINT (float, default 0.25) scales the tint of model materials only; world brushes use 0.5.
                const bool modelEnv = vertexLit || options.forModel;   // forModel: a world-shader R2 material the engine re-labels VertexLitGeneric for a converted model (r2m/)
                // World brushes: 0.5 (SplitCost, cubemaps split on: with the user's mat_envmap_scale 2 world reflections were +5 % mean luminance
                // over R2 (split 74.8, R2 71.2, single 67.4); at envmap scale 1 split matched R2 (70.9)).
                double k = modelEnv ? 0.25 : 0.5;
                if (puddleLayers) k = 9.0;   // measured with LightVerify on mp_glitch: prop brightness conv/R2 1.82 at 1, 1.56 at 0.25; mp_lf_stacks pelican crates: silver at 1
                if (hsWaterBody) k = 0.4;   // with the Fresnel keys below; measured against R2 at the two river poses, see hsWater
                if (modelEnv) if (const char* e = std::getenv("R2TEX_MODEL_ENVTINT")) k = std::clamp(std::atof(e), 0.0, 4.0);
                char tint[48];
                std::snprintf(tint, sizeof(tint), "[%g %g %g]", k, k, k);
                addVmtParam(out, "$envmaptint", tint);
                if (envTk.lightScale && envTokenSafe && !modelEnv && lightmapped) {   // VertexLitGeneric has no $envmapLightScale
                    char scale[32];
                    std::snprintf(scale, sizeof(scale), "%g", envTk.lightScaleValue);
                    addVmtParam(out, "$envmaplightscale", scale);
                    if (usedSlots.find(26) != usedSlots.end()) addVmtParam(out, "$envmaplightscale2", scale);
                }
                // Stock R1 weights the Fresnel term of the env reflection by t2.a (1 on every DXT1 `_spc`): a mirror at grazing angles on every
                // building. 0.35 = mean gloss^2 of the SUBSTATION wall, R2's own grazing maximum (maps/reflections/REFLECTIONS.md); opt-out R2TEX_ENV=off.
                if (envTk.fresnel > 0.0 && envTokenSafe && !modelEnv && lightmapped) {
                    char fresnel[32];
                    std::snprintf(fresnel, sizeof(fresnel), "%g", envTk.fresnel);
                    addVmtParam(out, "$fresnelamount", fresnel);
                }
                if (envTk.blur && glossBake) {
                    // probe lod = 6.5 + log2(1 / sqrt(exponent(alpha))), exponent(0) = $shininessBlack, exponent(1) = $shininessWhite
                    // (the engine's env lookup; at the defaults 0 / 255 the lod is mip 0 for every alpha). lod 6.5 - log2(sqrt(x)) = lod0 -> x = 2^(2 (6.5 - lod0)).
                    char black[32], white[32];
                    std::snprintf(black, sizeof(black), "%g", std::exp2(2.0 * (6.5 - envTk.blurLod0)));
                    std::snprintf(white, sizeof(white), "%g", std::exp2(2.0 * (6.5 + 1.0)));
                    addVmtParam(out, "$shininessblack", black);
                    addVmtParam(out, "$shininesswhite", white);
                }
            }
        }
        // R2 emissive = _ilm * emissive tint (float4 #10 rgb, black by default) * scale: "texture alone does not glow" (shaderlab/LIGHTING.md).
        // mp_complex3 stackable_cages01 has tint (0 0.8 0): green LED dots only, no glow elsewhere. R1 $selfillum with a mask glows the whole
        // mask-weighted albedo, so a black tint means no $selfillum at all; otherwise the tint goes to $selfIllumTint (HDR values capped at 4).
        if (vertexLit && usedSlots.find(4) != usedSlots.end()) {
            double emitTint[3] = {1.0, 1.0, 1.0};
            if (constants.size() >= 43)
                for (int i = 0; i < 3; ++i) emitTint[i] = std::isfinite(constants[40 + i]) ? std::clamp<double>(constants[40 + i], 0.0, 4.0) : 0.0;
            if (emitTint[0] + emitTint[1] + emitTint[2] > 0.004) {
                addVmtParam(out, "$selfillum", "1");
                param(4, "$selfIllumMask");
                if (std::fabs(emitTint[0] - 1.0) > 0.004 || std::fabs(emitTint[1] - 1.0) > 0.004 || std::fabs(emitTint[2] - 1.0) > 0.004) {
                    char tintText[64];
                    std::snprintf(tintText, sizeof(tintText), "[%.3f %.3f %.3f]", emitTint[0], emitTint[1], emitTint[2]);
                    addVmtParam(out, "$selfIllumTint", tintText);
                }
            }
        }
        param(14, "$detailColor");
        if (!unlit) param(15, "$detailNormal");
        if (referencedSlots.find(14) != referencedSlots.end() ||
            referencedSlots.find(15) != referencedSlots.end())
            addVmtParam(out, "$detailScale", "[1 1]");
        if (uberSingle) {
            addVmtParam(out, "$detailColor", vmtTextureName(uberPackName(0, uberAoGuid, uberCavityGuid)));
            addVmtParam(out, "$detailColorMode", "1");
            if (referencedSlots.find(15) == referencedSlots.end()) addVmtParam(out, "$detailScale", "[1 1]");
        }
        if (lightmapped) {
            if (effMode == LayerMode::maskRg || effMode == LayerMode::maskRgInv) {
                auto mask = usedSlots.find(22);
                if (mask != usedSlots.end())
                    mask->second = layerMaskName(slotGuids[22],
                        effMode == LayerMode::maskRg ? TextureTransform::maskRg : TextureTransform::maskRgInv);
            }
            if (uberLayered) {
                usedSlots[22] = uberPackName(slotGuids[22], uberAoGuid, uberCavityGuid);
                addVmtParam(out, "$treesway", "7701");
            }
            param(22, "$blendModulateTexture");
            param(23, "$baseTexture2");
            param(24, "$bumpmap2");
            param(26, "$reflectionTint2");
        }
        // R2 world/signs/beacon_screens/* sheets are UnlitGeneric overlays drawn over a real screen (mp_complex3 crane-room
        // tablets: crane_room_monitor_console_static, beacon_crane_screens underneath). The converted overlay came out as a
        // blown-out white, mirror-like panel that hid the screen and flickered against it: (1) it carried $envmap env_cubemap
        // (an unlit glass material has no business reflecting the sky; the same flat-white blow-out the kodai fake-screen
        // note above describes), (2) its R2 diffuse tint 2.0 added on top of the lit screen (additive, 2 x white UI strips
        // read as a milky sheet; tint 1 keeps the cyan UI crisp like R2), (3) it lies coplanar with the screen and needs the
        // decal polygon offset. Verified on mp_complex3 (-5052.56 -64.18 648.55): blown white -> cyan holo UI as R2.
        const bool screenOverlay = unlit && name.rfind("world/signs/beacon_screens/", 0) == 0;
        {
            // $color: R2 diffuse tint (constant buffer) times the baked mean of a flat sheet texture; $alpha: R2 opacity
            // (blended draw states only) times the flat sheet alpha mean.
            double color[3] = {materialTint[0], materialTint[1], materialTint[2]};
            double alpha = blendEnabled ? materialOpacity : 1.0;
            if (screenOverlay)
                for (double& c : color) c = std::min(c, 1.0);
            // HDR sky domes (BC6H albedo on an unlit material: homestead_se_a, eden_mp_HDR, timeshift_warm_sky; R2 cbuffer tint 4, 4,
            // 22). The texture is converted with a Reinhard curve (toneMapHdr) to 8 bit, so R1's $color multiplies already compressed
            // values: the full R2 tint clips the sky to white (mp_homestead p14: 60 % of the sky pixels >= 250, R2 p90 168). Measured on
            // mp_homestead against R2 at the same pose (sky box mean luminance R2 135 / 163 in the sun glare): $color 2 gives 125 / 144,
            // 2.5 gives 157 / 170, 4 gives 237 / 225 (clipped). 4^0.6 = 2.3 lands between; tints <= 1 (every other BC6H sky) are untouched.
            {
                bool hdrBase = false;
                if (unlit && !slotGuids.empty() && slotGuids[0]) {
                    if (const AssetRecord* tex = findRecord(*db, slotGuids[0], kTxtr)) {
                        std::vector<std::uint8_t> textureHeader;
                        std::string ignoredError;
                        auto textureFamily = db->getFamily(db->paks[tex->pakIndex].family, ignoredError);
                        if (textureFamily && readAssetHeader(*db, *tex, textureFamily, textureHeader, ignoredError) && textureHeader.size() >= 0x38) {
                            const std::uint16_t textureFormat = u16(textureHeader.data() + 0x16);
                            hdrBase = textureFormat == 10 || textureFormat == 11;
                        }
                    }
                }
                if (hdrBase)
                    for (double& c : color)
                        if (c > 1.0) c = std::pow(c, 0.6);
            }
            if (metalFromSpec)
                for (double& c : color) c *= kMetalAlbedoScale;
            if (darkGlassPane) {
                // Hue: R2's pane is greyer than its tint (R/G 0.80, B/G 1.09 against the tint's 0.65 / 1.08: the reflection of the neutral sky
                // adds to the diffuse). Measured with the plain gain on the user's pose the converted pane came out R/G 0.65. Pull the tint
                // 45 % toward its luminance (luminance kept), then apply the gain.
                constexpr double kDarkGlassDesaturate = 0.45;
                const double tintLuma = 0.2126 * color[0] + 0.7152 * color[1] + 0.0722 * color[2];
                for (double& c : color) c = (c + kDarkGlassDesaturate * (tintLuma - c)) * darkGlassGain;
            }
            // mp_complex3 cypress leaves (tree_cypress_tall_leaves_01) in the building shadows are lit by ambient only, R2 also
            // lights them through its leaf translucency, which R1 lacks; the blue haze then dominates the leaf pixels and the
            // trees read blue (more so with distance). Mean leaf-pixel RGB, R2 / R1 gain 1.0 / R1 gain 1.5, same camera:
            // user spot (-1217 -1493 632) 15.7 15.7 25.0 / 12.6 13.0 24.2 / 17.8 19.2 27.3; 450 units 18.3 20.4 29.8 / 11.4 12.2
            // 23.0 / 18.7 20.2 27.3; 2200 units 53.6 55.3 57.6 / 45.3 45.0 46.4 / 52.5 52.9 51.2. Measured on this material only.
            if (foliageCavity && name.find("tree_cypress_tall_leaves") != std::string::npos)
                for (double& c : color) c *= 1.5;
            if (softCloudSheet) alpha *= softCloudAlpha;
            if (kodaiLowerCloudRing) alpha = 0.0;
            if (puddleLayers) { color[0] *= 0.5; color[1] *= 0.55; color[2] *= 0.65; }
            // Homestead river (see hsWater above). Body: alpha 0.85 -> 0.6, cool dark tint; foam: alpha 0.4 and a slightly dimmed tint.
            if (hsWaterBody) { alpha *= 0.7; color[0] *= 0.65; color[1] *= 0.68; color[2] *= 0.78; }
            if (hsWaterFoam) { alpha *= 0.4; color[0] *= 0.75; color[1] *= 0.75; color[2] *= 0.78; }
            if (flatSheet.ok) {
                for (int i = 0; i < 3; ++i) color[i] *= flatSheet.rgb[i];
                alpha *= flatSheet.alpha;
            }
            char text[96];
            if (flatSheet.ok || std::fabs(color[0] - 1.0) > 0.004 || std::fabs(color[1] - 1.0) > 0.004 ||
                std::fabs(color[2] - 1.0) > 0.004) {
                std::snprintf(text, sizeof(text), "[%.3f %.3f %.3f]", color[0], color[1], color[2]);
                addVmtParam(out, "$color", text);
            }
            if (flatSheet.ok || alpha < 0.996) {
                std::snprintf(text, sizeof(text), "%.3f", alpha);
                addVmtParam(out, "$alpha", text);
            }
        }
        if (cut) {
            addVmtParam(out, "$alphatest", "1");
            // The converter's fixed reference 0.7 (tuned on foliage) rejects a stencil atlas whose visible texels sit below it: the
            // mp_forwardbase_kodai container decals world/mcor/kodai_ind_decals_01 (the "IMC INDUSTRIES" logo and text, labels, stripes) have alpha
            // 176/255 = 0.69 inside the glyphs, so 0.15 percent of the visible texels passed and every decal was invisible (R2 draws them).
            // R2 stores its own reference in material constant #38 (0.5 on 148 of the 160 cut materials of the 20 maps, 0.2 on imc_int_decals,
            // 0.8 on ascent_asphalt_stripes_01; 0 on every non-cut material). When fewer than half of the visible albedo texels reach 0.7 and R2's
            // reference is lower, that reference is used. Materials whose albedo clears 0.7 keep it. R2TEX_CUT_REF=0 keeps 0.7 everywhere.
            double alphaRef = 0.7;
            const char* cutRefEnv = std::getenv("R2TEX_CUT_REF");
            if (!(cutRefEnv && std::atoi(cutRefEnv) == 0) && !foliageCavity && !opacityMap && constants.size() > 38 &&
                std::isfinite(constants[38]) && constants[38] > 0.05f && constants[38] < 0.7f && !slotGuids.empty() && slotGuids[0]) {
                const AssetRecord* albedoRecord = findRecord(*db, slotGuids[0], kTxtr);
                std::vector<std::uint8_t> albedoVtf;
                std::string textureWhy;
                double share = 1.0;
                if (albedoRecord && convertTextureWithDb(db, *albedoRecord, TextureOptions{}, albedoVtf, textureWhy) &&
                    vtfTopMipVisibleShareAtOrAbove(albedoVtf, 179, share) && share < 0.5)
                    alphaRef = constants[38];
            }
            char refText[32];
            std::snprintf(refText, sizeof(refText), "%.2f", alphaRef);
            addVmtParam(out, "$alphaTestReference", refText);
        }
        if (additive) addVmtParam(out, "$additive", "1");
        else if (translucent || glass) addVmtParam(out, "$translucent", "1");
        if (godray) addVmtParam(out, "$translucent", "1");
        if (decal || screenOverlay) addVmtParam(out, "$decal", "1");
        if ((glass && !unlit) || (!unlit && !foliageNoEnv && usedSlots.find(3) != usedSlots.end())) addVmtParam(out, "$envmap", "env_cubemap");
        if (puddleLayers) {
            addVmtParam(out, "$fresnelamount", "1");
            addVmtParam(out, "$fresnelintensity", "1");
            addVmtParam(out, "$fresnelcurvesharpness", "0.01");
            addVmtParam(out, "$envmapfresnel", "1");
            addVmtParam(out, "$envmaplambertian", "0");
        }
        // Homestead river body: R1 Fresnel environment term (the stock R1 river props water_sb_03 / water_sb_foamy_01 use the same keys).
        if (hsWaterBody) {
            addVmtParam(out, "$fresnelamount", "1");
            addVmtParam(out, "$fresnelintensity", "2");
            addVmtParam(out, "$fresnelcurvesharpness", "0.01");
            addVmtParam(out, "$envmapfresnel", "1");
            addVmtParam(out, "$envmaplambertian", "2");
        }
        // A layered R2 material uses vertex alpha as the layer blend weight. Once its layers are removed (layers-off),
        // R1 would multiply that graded alpha into the opaque surface and dither it: the mp_glitch ground shimmered
        // (metric 2.5..3.9) with "$vertexcolor 1" and not (0.0) without it.
        // World (BSP) materials that are opaque and have no second layer: their vertex colour is white (rgb 255 on all of
        // mp_eden's) while the vertex alpha can be graded (33 such materials, 343k vertices over 21 maps), and R1 reads that
        // alpha as dithered opacity. Drop $vertexcolor there; `models/` materials keep it (baked tint, rgb about 110).
        const bool whiteVertexWorld = lightmapped && !hasLayerSlots && opaqueAlbedo && name.rfind("world/", 0) == 0 && !tintedVertexWorldMaterial(name);
        if (shaderSet.find("vcolt") != std::string::npos && !layersOff && !whiteVertexWorld)
            addVmtParam(out, "$vertexcolor", "1");
        if (shaderSet.find("vcola") != std::string::npos && !dropVertexAlpha) addVmtParam(out, "$vertexalpha", "1");
        if ((raster & 0x06u) == 0x02u) addVmtParam(out, "$nocull", "1");
        // R2 UV animation. Shader sets with Uv<k>at tokens carry, per UV set k (1..3), a 2x2 matrix and a scroll velocity in the
        // CPU constants (6 floats per set: m00 m01 m10 m11 vx vy; UV units per second, checked on homestead_water_01 /
        // whtwsh_btt against R2 frames: the foam drifts the same way and about as fast as with this proxy). The "UV<n><digits>"
        // token before "Samp" gives the UV set of every bound texture slot in ascending slot order. Only a scrolling albedo
        // (slot 0) can be reproduced: R1 world and model shaders have a base transform but no separate bump or detail
        // transform, so materials that scroll only their normal maps (the *_flowing / *_distortion family) are left static.
        // The VMT uses TextureTransform (scaleVar $r2uvscale, translateVar $r2uvshift, result $basetexturetransform) with one
        // LinearRamp per velocity component writing $r2uvshift[0|1]: R1's TextureScroll proxy overwrites the whole transform
        // matrix and loses the scale (tested: scale 0.25 and 4 looked identical), this chain keeps it. Direction: R2 and R1
        // foam drift compared on mp_homestead with the velocity used as-is (translate += v * t), no sign flip.
        if (!hasLayerSlots && !flatSheet.ok && constants.size() >= 6) {
            const std::size_t samp = shaderSet.find("samp");
            std::size_t digitsBegin = samp;
            while (samp != std::string::npos && digitsBegin > 0 && std::isdigit(static_cast<unsigned char>(shaderSet[digitsBegin - 1]))) --digitsBegin;
            if (samp != std::string::npos && samp - digitsBegin >= 2 && digitsBegin >= 2 && shaderSet.compare(digitsBegin - 2, 2, "uv") == 0) {
                std::size_t digitIndex = 0;
                int set = 0;
                for (std::size_t slot = 0; slot < slotGuids.size(); ++slot) {
                    if (!slotGuids[slot]) continue;
                    if (slot == 0) { set = shaderSet[digitsBegin + 1 + digitIndex] - '0'; break; }
                    ++digitIndex;
                }
                if (digitsBegin + 1 + digitIndex < samp && set >= 1 && set <= 3 &&
                    constants.size() >= static_cast<std::size_t>(set) * 6) {
                    const bool animatedSet = shaderSet.find("uv" + std::to_string(set) + "at") != std::string::npos;
                    const float* c = constants.data() + (set - 1) * 6;
                    bool sane = true;
                    for (int i = 0; i < 6; ++i) sane = sane && std::isfinite(c[i]);
                    const double speed = std::hypot(c[4], c[5]);
                    const bool matrixOk = sane && c[0] > 0.01f && c[0] < 64.0f && c[3] > 0.01f && c[3] < 64.0f &&
                        std::fabs(c[1]) < 1e-3f && std::fabs(c[2]) < 1e-3f;
                    if (animatedSet && matrixOk && speed > 1e-4 && speed < 16.0) {
                        char text[160];
                        std::snprintf(text, sizeof(text), "[%.5g %.5g]", c[0], c[3]);
                        addVmtParam(out, "$r2uvscale", text);
                        addVmtParam(out, "$r2uvshift", "[0 0]");
                        addVmtParam(out, "$basetexturetransform", "center 0 0 scale 1 1 rotate 0 translate 0 0");
                        out << "\t\"Proxies\"\n\t{\n";
                        for (int axis = 0; axis < 2; ++axis) {
                            if (std::fabs(c[4 + axis]) < 1e-5f) continue;
                            std::snprintf(text, sizeof(text), "%.6g", c[4 + axis]);
                            out << "\t\t\"LinearRamp\"\n\t\t{\n\t\t\t\"rate\" \"" << text << "\"\n\t\t\t\"initialValue\" \"0\"\n\t\t\t\"resultVar\" \"$r2uvshift["
                                << axis << "]\"\n\t\t}\n";
                        }
                        out << "\t\t\"TextureTransform\"\n\t\t{\n\t\t\t\"translateVar\" \"$r2uvshift\"\n\t\t\t\"scaleVar\" \"$r2uvscale\"\n"
                            << "\t\t\t\"resultVar\" \"$basetexturetransform\"\n\t\t}\n\t}\n";
                    } else if (matrixOk && speed < 1e-4 && (std::fabs(c[0] - 1.0f) > 1e-3f || std::fabs(c[3] - 1.0f) > 1e-3f)) {
                        // Static UV scale. The R2 vista models (homestead_sky, crashsite3, drydock, kodai, BWC) store UVs that only
                        // cover 1/m11 of the texture height (homestead_se_c: V 0.76..1.0 with m11 4; homestead_se_b: V 0.50..1.0 with
                        // m11 2) and the shader multiplies them back with this matrix, wrapping to 0..1. Without it R1 samples only the
                        // bottom strip of the panorama stretched 2x to 4x (blocky, flat 3D sky mountains). center 0 0 gives v' = m11 * v.
                        char text[160];
                        std::snprintf(text, sizeof(text), "center 0 0 scale %.5g %.5g rotate 0 translate 0 0", c[0], c[3]);
                        addVmtParam(out, "$basetexturetransform", text);
                    }
                }
            }
        }
    }
    out << "}\n";

    material.name = name;
    material.vmt = out.str();
    material.textures.clear();
    for (const auto& pair : usedSlots) {
        const std::size_t slot = pair.first;
        if (slot >= slotGuids.size() || referencedSlots.find(slot) == referencedSlots.end()) continue;
        TextureRef texture;
        texture.guid = slotGuids[slot];
        texture.name = pair.second;
        texture.slot = static_cast<std::uint32_t>(slot);
        if (slot == 22 && (effMode == LayerMode::maskRg || effMode == LayerMode::maskRgInv)) {
            texture.transform = effMode == LayerMode::maskRg ?
                TextureTransform::maskRg : TextureTransform::maskRgInv;
        }
        if (opaqueAlbedo && (slot == 0 || slot == 23)) texture.transform = TextureTransform::opaqueAlpha;
        if ((opacityMap || foliageCavity) && slot == 0) texture.transform = TextureTransform::opacityMerge;
        if (normalRepack && (slot == 1 || slot == 24)) texture.transform = TextureTransform::normalRgb;
        if (uberLayered && slot == 22) texture.transform = TextureTransform::uberPack;
        if (glossBake && slot == 3) texture.transform = TextureTransform::specGloss;
        if (gloss2Bake && slot == 26) texture.transform = TextureTransform::specGloss;
        material.textures.push_back(std::move(texture));
    }
    if (uberSingle) {
        TextureRef pack;
        pack.guid = uberAoGuid ? uberAoGuid : uberCavityGuid;
        pack.name = uberPackName(0, uberAoGuid, uberCavityGuid);
        pack.slot = uberAoGuid ? 11 : 12;
        pack.transform = TextureTransform::uberPack;
        material.textures.push_back(std::move(pack));
    }
    return true;
}

bool parseBspNames(const std::uint8_t* data, std::size_t byteCount,
                   std::vector<std::string>& names, std::string& error) {
    if (!data && byteCount) { error = "null BSP buffer"; return false; }
    constexpr std::size_t headerBytes = 16 + 128 * 16;
    if (byteCount < headerBytes || !data || std::memcmp(data, "rBSP", 4) != 0) {
        error = "not a Titanfall Respawn BSP";
        return false;
    }
    const std::uint32_t version = u32(data + 4);
    const std::uint32_t lumpCount = u32(data + 12);
    if (version < 29 || version > 0x10000 || lumpCount != 127) {
        error = "unsupported Respawn BSP header";
        return false;
    }
    struct Lump { std::uint32_t offset, length; } lumps[128]{};
    for (std::uint32_t i = 0; i < 128; ++i) {
        const std::uint8_t* p = data + 16 + i * 16;
        lumps[i] = {u32(p), u32(p + 4)};
        if (lumps[i].offset > byteCount || lumps[i].length > byteCount - lumps[i].offset) {
            error = "BSP lump outside file";
            return false;
        }
    }
    const Lump td = lumps[kBspTextureData];
    const Lump stringData = lumps[kBspTextureNameData];
    const Lump stringTable = lumps[kBspTextureNameTable];
    if (td.length % 36 || stringTable.length % 4) {
        error = "invalid BSP texture lump sizes";
        return false;
    }
    const std::uint8_t* stringBytes = data + stringData.offset;
    const std::uint32_t tableCount = stringTable.length / 4;
    std::vector<std::uint32_t> offsets(tableCount);
    for (std::uint32_t i = 0; i < tableCount; ++i)
        offsets[i] = u32(data + stringTable.offset + i * 4);
    std::set<std::string> unique;
    const std::uint32_t recordCount = td.length / 36;
    for (std::uint32_t i = 0; i < recordCount; ++i) {
        const std::int32_t index = static_cast<std::int32_t>(u32(data + td.offset + i * 36 + 12));
        if (index < 0 || static_cast<std::uint32_t>(index) >= tableCount) continue;
        const std::uint32_t offset = offsets[static_cast<std::uint32_t>(index)];
        if (offset >= stringData.length) continue;
        const char* start = reinterpret_cast<const char*>(stringBytes + offset);
        const std::size_t avail = stringData.length - offset;
        const void* end = std::memchr(start, 0, avail);
        if (!end) continue;
        const std::size_t nameSize = static_cast<const char*>(end) - start;
        if (!nameSize || nameSize > 4096) continue;
        std::string name(start, nameSize);
        name = cleanAssetName(name, true);
        if (validAssetName(name)) unique.insert(std::move(name));
    }
    names.assign(unique.begin(), unique.end());
    if (names.empty()) { error = "BSP contains no material names"; return false; }
    error.clear();
    return true;
}

bool parseBspNames(const fs::path& path, std::vector<std::string>& names, std::string& error) {
    std::vector<std::uint8_t> bytes;
    if (!readWholeFile(path, bytes, error)) return false;
    return parseBspNames(bytes.data(), bytes.size(), names, error);
}

