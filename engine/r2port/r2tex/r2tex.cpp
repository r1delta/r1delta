bool convertTextureWithDb(const std::shared_ptr<Database>& db, const AssetRecord& record,
                          const TextureOptions& options, std::vector<std::uint8_t>& vtf,
                          std::string& error) {
    auto family = db->getFamily(db->paks[record.pakIndex].family, error);
    if (!family) return false;
    std::vector<std::uint8_t> header;
    if (!readAssetHeader(*db, record, family, header, error)) return false;
    if (header.size() < 0x38) { error = "short txtr header"; return false; }
    const std::uint16_t width = u16(header.data() + 0x10);
    const std::uint16_t height = u16(header.data() + 0x12);
    const std::uint16_t depth = u16(header.data() + 0x14);
    const std::uint16_t format = u16(header.data() + 0x16);
    const std::uint32_t declaredDataSize = u32(header.data() + 0x18);
    const std::uint8_t opt = header[0x1d];
    const std::uint8_t arraySize = header[0x1e];
    const std::uint8_t layers = header[0x1f];
    const std::uint8_t perm = header[0x21];
    const std::uint8_t streamed = header[0x22];
    if (!width || !height || depth || arraySize || layers || !perm || opt) {
        error = "unsupported txtr dimensions, array, or optional mips"; return false;
    }
    const std::uint32_t count = static_cast<std::uint32_t>(opt) + perm + streamed;
    if (!count || count > 32 || count > 255) { error = "invalid txtr mip count"; return false; }
    const FormatInfo info = sourceFormat(format);
    if (!info.bytes) { error = "unsupported R2 texture format " + std::to_string(format); return false; }
    std::vector<ImageMip> images(count);
    const PakData* assetOwner = findPakOwner(*family, record.pakIndex);
    if (!assetOwner) { error = "texture pak is unavailable"; return false; }
    std::uint64_t permanentSize = 0;
    for (int m = static_cast<int>(count) - 1; m >= static_cast<int>(opt + streamed); --m) {
        const std::uint32_t mw = std::max(1u, static_cast<std::uint32_t>(width) >> m);
        const std::uint32_t mh = std::max(1u, static_cast<std::uint32_t>(height) >> m);
        const std::size_t raw = mipSize(format, mw, mh);
        if (!raw || permanentSize > std::numeric_limits<std::uint64_t>::max() - aligned16(raw)) {
            error = "invalid permanent mip size"; return false;
        }
        permanentSize += aligned16(raw);
        images[static_cast<std::size_t>(m)].width = mw;
        images[static_cast<std::size_t>(m)].height = mh;
    }
    if (permanentSize > std::numeric_limits<std::size_t>::max()) { error = "permanent mip data is too large"; return false; }
    if (declaredDataSize && permanentSize > declaredDataSize) {
        error = "permanent txtr data exceeds declared dataSize"; return false;
    }
    std::vector<std::uint8_t> permanentData;
    if (!readPageRange(*family, *assetOwner, record.data, static_cast<std::size_t>(permanentSize), permanentData, error)) return false;
    std::size_t permanentOffset = 0;
    for (int m = static_cast<int>(count) - 1; m >= static_cast<int>(opt + streamed); --m) {
        const auto& img = images[static_cast<std::size_t>(m)];
        const std::size_t raw = mipSize(format, img.width, img.height);
        if (permanentOffset > permanentData.size() || raw > permanentData.size() - permanentOffset) {
            error = "permanent mip range invalid"; return false;
        }
        images[static_cast<std::size_t>(m)].bytes.assign(
            permanentData.begin() + permanentOffset, permanentData.begin() + permanentOffset + raw);
        permanentOffset += aligned16(raw);
    }
    if (streamed) {
        if (record.starpakOffset < 0) { error = "streamed mips have no starpak offset"; return false; }
        const PakData* owner = assetOwner;
        if (!owner) { error = "texture pak is unavailable"; return false; }
        const auto starIndex = static_cast<std::uint32_t>(static_cast<std::uint64_t>(record.starpakOffset) & 0xfffu);
        const std::uint64_t starOffset = static_cast<std::uint64_t>(record.starpakOffset) & ~std::uint64_t(0xfffu);
        if (starIndex >= owner->starpaks.size()) { error = "starpak index is out of range"; return false; }
        fs::path starPath = db->pakDir / fs::u8path(owner->starpaks[starIndex]).filename();
        std::uint64_t streamBytes = 0;
        for (int m = static_cast<int>(opt + streamed) - 1; m >= static_cast<int>(opt); --m) {
            const std::uint32_t mw = std::max(1u, static_cast<std::uint32_t>(width) >> m);
            const std::uint32_t mh = std::max(1u, static_cast<std::uint32_t>(height) >> m);
            const auto raw = mipSize(format, mw, mh);
            if (!raw || streamBytes > std::numeric_limits<std::uint64_t>::max() - aligned16(raw)) { error = "streamed mip size overflow"; return false; }
            streamBytes += aligned16(raw);
        }
        if (streamBytes > std::numeric_limits<std::size_t>::max() || starOffset > std::numeric_limits<std::uint64_t>::max() - streamBytes) {
            error = "streamed mip range overflow"; return false;
        }
        std::vector<std::uint8_t> streamedData(static_cast<std::size_t>(streamBytes));
        if (!readAtExact(starPath, starOffset, streamedData.data(), streamedData.size(), error)) return false;
        std::size_t sourceOffset = 0;
        for (int m = static_cast<int>(opt + streamed) - 1; m >= static_cast<int>(opt); --m) {
            const std::uint32_t mw = std::max(1u, static_cast<std::uint32_t>(width) >> m);
            const std::uint32_t mh = std::max(1u, static_cast<std::uint32_t>(height) >> m);
            const std::size_t raw = mipSize(format, mw, mh);
            const std::size_t padded = aligned16(raw);
            ImageMip& img = images[static_cast<std::size_t>(m)];
            img.width = mw; img.height = mh;
            img.bytes.assign(streamedData.begin() + sourceOffset, streamedData.begin() + sourceOffset + raw);
            sourceOffset += padded;
        }
    }

    std::uint16_t imageFormat = 0xffff;
    std::uint32_t flags = isNormalName(record.name) ? 0x80u : 0u;
    const bool passBc7 = (format == 12 || format == 13) && options.bc7Passthrough;
    const bool passBc6h = (format == 10 || format == 11) && options.bc6hPassthrough;
    std::vector<ImageMip> converted;
    if (passBc7 || passBc6h) {
        imageFormat = passBc7 ? 67 : 66;
        if (passBc7) {
            flags |= 0x2000u;
            if (format == 13) flags |= 0x80000u;
        }
        converted = std::move(images);
    } else {
        converted.resize(count);
        for (std::uint32_t m = 0; m < count; ++m) {
            if (images[m].bytes.empty()) { error = "missing mip " + std::to_string(m); return false; }
            std::uint16_t thisFormat = 0xffff;
            std::uint32_t thisFlags = flags;
            if (!decodeMip(format, images[m].width, images[m].height, images[m].bytes.data(), images[m].bytes.size(),
                           thisFormat, thisFlags, converted[m], error)) return false;
            if (imageFormat == 0xffff) imageFormat = thisFormat;
            else if (imageFormat != thisFormat) { error = "inconsistent converted mip format"; return false; }
            flags |= thisFlags;
        }
    }
    std::uint64_t totalSize = 0x58;
    for (const auto& mip : converted) {
        if (mip.bytes.size() > std::numeric_limits<std::uint64_t>::max() - totalSize) { error = "VTF size overflow"; return false; }
        totalSize += mip.bytes.size();
    }
    if (totalSize > std::numeric_limits<std::size_t>::max()) { error = "VTF too large"; return false; }
    vtf.assign(static_cast<std::size_t>(totalSize), 0);
    std::memcpy(vtf.data(), "VTF\0", 4);
    put32(vtf.data() + 4, 7); put32(vtf.data() + 8, 5); put32(vtf.data() + 12, 0x58);
    put16(vtf.data() + 0x10, width); put16(vtf.data() + 0x12, height); put32(vtf.data() + 0x14, flags);
    put16(vtf.data() + 0x18, 1); put16(vtf.data() + 0x1a, 0);
    putFloat(vtf.data() + 0x20, 0.5f); putFloat(vtf.data() + 0x24, 0.5f); putFloat(vtf.data() + 0x28, 0.5f);
    putFloat(vtf.data() + 0x30, 1.0f);
    putI32(vtf.data() + 0x34, static_cast<std::int32_t>(imageFormat));
    vtf[0x38] = static_cast<std::uint8_t>(count);
    putI32(vtf.data() + 0x39, -1); vtf[0x3d] = 0; vtf[0x3e] = 0; put16(vtf.data() + 0x3f, 1);
    put32(vtf.data() + 0x44, 1);
    vtf[0x50] = 0x30; vtf[0x51] = 0; vtf[0x52] = 0; vtf[0x53] = 0; put32(vtf.data() + 0x54, 0x58);
    std::size_t outOffset = 0x58;
    for (int m = static_cast<int>(count) - 1; m >= 0; --m) {
        const auto& bytes = converted[static_cast<std::size_t>(m)].bytes;
        std::memcpy(vtf.data() + outOffset, bytes.data(), bytes.size());
        outOffset += bytes.size();
    }
    return addMipChain(vtf, record.name);
}

bool expandLayerMaskVtf(std::vector<std::uint8_t>& vtf, bool invert, std::string& error) {
    if (vtf.size() < 0x58 || std::memcmp(vtf.data(), "VTF\0", 4) != 0) {
        error = "invalid source VTF for layer mask";
        return false;
    }
    const std::uint32_t width = u16(vtf.data() + 0x10);
    const std::uint32_t height = u16(vtf.data() + 0x12);
    const std::uint32_t mipCount = vtf[0x38];
    const std::uint32_t format = u32(vtf.data() + 0x34);
    const std::uint32_t sourceOffset = u32(vtf.data() + 0x54);
    if (!width || !height || !mipCount || mipCount > 32 || sourceOffset < 0x58 ||
        sourceOffset > vtf.size()) {
        error = "invalid source VTF dimensions for layer mask";
        return false;
    }

    std::uint64_t outputSize = 0x58;
    for (std::uint32_t m = mipCount; m-- > 0;) {
        const std::uint64_t w = std::max(1u, width >> m);
        const std::uint64_t h = std::max(1u, height >> m);
        if (w > (std::numeric_limits<std::size_t>::max() - outputSize) / (h * 4)) {
            error = "expanded layer mask is too large";
            return false;
        }
        outputSize += w * h * 4;
    }
    if (outputSize > std::numeric_limits<std::size_t>::max()) {
        error = "expanded layer mask is too large";
        return false;
    }
    std::vector<std::uint8_t> expanded(static_cast<std::size_t>(outputSize), 0);
    std::memcpy(expanded.data(), vtf.data(), 0x58);
    put32(expanded.data() + 0x14, u32(vtf.data() + 0x14) & 0x0cu);
    putI32(expanded.data() + 0x34, 0);
    put32(expanded.data() + 0x54, 0x58);

    std::size_t input = sourceOffset;
    std::size_t output = 0x58;
    for (std::uint32_t m = mipCount; m-- > 0;) {
        const std::uint32_t w = std::max(1u, width >> m);
        const std::uint32_t h = std::max(1u, height >> m);
        const std::uint32_t blocksX = (w + 3) / 4;
        const std::uint32_t blocksY = (h + 3) / 4;
        std::size_t sourceBlockBytes = 0;
        if (format == 35) sourceBlockBytes = 8;
        else if (format == 13) sourceBlockBytes = 8;
        else if (format == 14 || format == 15 || format == 34) sourceBlockBytes = 16;
        std::size_t mipSourceBytes = 0;
        if (sourceBlockBytes) {
            if (static_cast<std::uint64_t>(blocksX) * blocksY >
                std::numeric_limits<std::size_t>::max() / sourceBlockBytes) {
                error = "layer mask mip size overflow";
                return false;
            }
            mipSourceBytes = static_cast<std::size_t>(blocksX) * blocksY * sourceBlockBytes;
        } else if (format == 0 || format == 8) {
            const std::size_t pixelBytes = format == 0 ? 4 : 3;
            if (static_cast<std::uint64_t>(w) * h >
                std::numeric_limits<std::size_t>::max() / pixelBytes) {
                error = "layer mask mip size overflow";
                return false;
            }
            mipSourceBytes = static_cast<std::size_t>(w) * h * pixelBytes;
        } else {
            error = "layer mask source VTF format " + std::to_string(format) + " is unsupported";
            return false;
        }
        if (input > vtf.size() || mipSourceBytes > vtf.size() - input) {
            error = "truncated source VTF layer mask mip";
            return false;
        }
        if (format == 0 || format == 8) {
            const std::size_t pixelBytes = format == 0 ? 4 : 3;
            for (std::uint32_t y = 0; y < h; ++y) {
                for (std::uint32_t x = 0; x < w; ++x) {
                    const std::size_t p = static_cast<std::size_t>(y) * w + x;
                    const std::uint8_t value = vtf[input + p * pixelBytes + (format == 0 ? 0 : 2)];
                    const std::uint8_t mask = invert ? static_cast<std::uint8_t>(255u - value) : value;
                    std::uint8_t* dst = expanded.data() + output + p * 4;
                    dst[0] = mask; dst[1] = mask; dst[2] = 0; dst[3] = 255;
                }
            }
        } else {
            std::array<std::uint8_t, 64> rgba{};
            std::array<std::uint8_t, 32> rg{};
            std::array<std::uint8_t, 16> r{};
            for (std::uint32_t by = 0; by < blocksY; ++by) {
                for (std::uint32_t bx = 0; bx < blocksX; ++bx) {
                    const std::uint8_t* block = vtf.data() + input +
                        (static_cast<std::size_t>(by) * blocksX + bx) * sourceBlockBytes;
                    if (format == 35) bcdec_bc4(block, r.data(), 4, 0);
                    else if (format == 34) bcdec_bc5(block, rg.data(), 8, 0);
                    else if (format == 13) bcdec_bc1(block, rgba.data(), 16);
                    else if (format == 14) bcdec_bc2(block, rgba.data(), 16);
                    else bcdec_bc3(block, rgba.data(), 16);
                    for (std::uint32_t py = 0; py < 4 && by * 4 + py < h; ++py) {
                        for (std::uint32_t px = 0; px < 4 && bx * 4 + px < w; ++px) {
                            const std::size_t local = static_cast<std::size_t>(py) * 4 + px;
                            const std::uint8_t value = format == 35 ? r[local] :
                                format == 34 ? rg[local * 2] : rgba[local * 4];
                            const std::uint8_t mask = invert ? static_cast<std::uint8_t>(255u - value) : value;
                            const std::size_t pixel = static_cast<std::size_t>(by * 4 + py) * w + bx * 4 + px;
                            std::uint8_t* dst = expanded.data() + output + pixel * 4;
                            dst[0] = mask; dst[1] = mask; dst[2] = 0; dst[3] = 255;
                        }
                    }
                }
            }
        }
        input += mipSourceBytes;
        output += static_cast<std::size_t>(w) * h * 4;
    }
    vtf = std::move(expanded);
    return true;
}

std::string layerMaskName(std::uint64_t guid, TextureTransform transform) {
    std::ostringstream name;
    name << "r2tex/layer_masks/" << std::hex << std::setw(16) << std::setfill('0') << guid
         << (transform == TextureTransform::maskRg ? "_rg" : "_rg_inv");
    return name.str();
}

// R2 albedo textures (BC7 in particular) carry non-opacity data in the alpha channel. R1 reads the base texture alpha of
// an opaque lightmapped/vertex-lit material as screen-door (dithered) transparency, which flickers every frame: this is the
// "shimmer" (heat-mirage wobble, ghost shadow copies; gone with csm_enabled 0 + mat_global_lighting 1). Materials that
// are not translucent, additive or alpha-tested therefore reference an alias whose alpha is forced to 255.
constexpr const char* kOpaqueAlbedoPrefix = "r2tex/opaque/";

std::string opaqueAlbedoName(const std::string& textureName) {
    return std::string(kOpaqueAlbedoPrefix) + cleanAssetName(textureName, true);
}

bool forceOpaqueVtf(std::vector<std::uint8_t>& vtf, std::string& error) {
    if (vtf.size() < 0x58 || std::memcmp(vtf.data(), "VTF\0", 4) != 0) {
        error = "invalid source VTF for opaque albedo";
        return false;
    }
    const std::uint32_t width = u16(vtf.data() + 0x10);
    const std::uint32_t height = u16(vtf.data() + 0x12);
    const std::uint32_t mipCount = vtf[0x38];
    const std::uint32_t format = u32(vtf.data() + 0x34);
    std::size_t offset = u32(vtf.data() + 0x54);
    if (!width || !height || !mipCount || mipCount > 32 || offset < 0x58 || offset > vtf.size()) {
        error = "invalid source VTF dimensions for opaque albedo";
        return false;
    }
    if (format != 0 && format != 14 && format != 15) return true;  // no alpha channel to clear
    for (std::uint32_t m = mipCount; m-- > 0;) {
        const std::uint32_t w = std::max(1u, width >> m);
        const std::uint32_t h = std::max(1u, height >> m);
        std::size_t mipBytes;
        if (format == 0) mipBytes = static_cast<std::size_t>(w) * h * 4;
        else mipBytes = static_cast<std::size_t>((w + 3) / 4) * ((h + 3) / 4) * 16;
        if (offset > vtf.size() || mipBytes > vtf.size() - offset) {
            error = "truncated source VTF opaque albedo mip";
            return false;
        }
        std::uint8_t* mip = vtf.data() + offset;
        if (format == 0) {
            for (std::size_t p = 3; p < mipBytes; p += 4) mip[p] = 255;
        } else {
            for (std::size_t block = 0; block < mipBytes; block += 16) {
                if (format == 14) {
                    std::memset(mip + block, 0xff, 8);  // DXT3: sixteen 4 bit alpha values
                } else {
                    mip[block] = 255; mip[block + 1] = 255;  // DXT5: alpha0 == alpha1 == 255, all indices 0
                    std::memset(mip + block + 2, 0, 6);
                }
            }
        }
        offset += mipBytes;
    }
    return true;
}

// R2 "Opam" shader sets (45 materials over the 20 maps: grates, nets, decals, glass, signs) take opacity from a separate
// opacity map in slot 13. R1 reads opacity from the base texture alpha, so the opacity map is merged into the albedo
// alpha (alpha = albedo alpha * opacity, both 0..1) and the albedo is emitted as RGBA8.
constexpr const char* kOpacityMergePrefix = "r2tex/opamerge/";

// Name: r2tex/opamerge/<albedo guid>_<opacity guid>[_<cavity guid>]. An opacity guid of 0 means "no opacity map" (the
// albedo alpha is the opacity); a cavity guid selects the foliage bake (buildFoliageVtf).
std::string opacityMergeName(std::uint64_t albedoGuid, std::uint64_t opacityGuid, std::uint64_t cavityGuid = 0) {
    std::ostringstream name;
    name << kOpacityMergePrefix << std::hex << std::setw(16) << std::setfill('0') << albedoGuid << '_'
         << std::setw(16) << std::setfill('0') << opacityGuid;
    if (cavityGuid) name << '_' << std::setw(16) << std::setfill('0') << cavityGuid;
    return name.str();
}

bool parseOpacityMergeName(const std::string& name, std::uint64_t& albedoGuid, std::uint64_t& opacityGuid,
                           std::uint64_t* cavityGuid = nullptr) {
    const std::size_t prefix = std::strlen(kOpacityMergePrefix);
    if (cavityGuid) *cavityGuid = 0;
    const bool withCavity = name.size() == prefix + 16 + 1 + 16 + 1 + 16;
    if (name.rfind(kOpacityMergePrefix, 0) != 0 || (name.size() != prefix + 16 + 1 + 16 && !withCavity) ||
        name[prefix + 16] != '_' || (withCavity && name[prefix + 33] != '_'))
        return false;
    char* end = nullptr;
    const std::string a = name.substr(prefix, 16), b = name.substr(prefix + 17, 16);
    albedoGuid = std::strtoull(a.c_str(), &end, 16);
    if (end != a.c_str() + 16) return false;
    opacityGuid = std::strtoull(b.c_str(), &end, 16);
    if (end != b.c_str() + 16) return false;
    if (withCavity) {
        const std::string c = name.substr(prefix + 34, 16);
        const std::uint64_t guid = std::strtoull(c.c_str(), &end, 16);
        if (end != c.c_str() + 16) return false;
        if (cavityGuid) *cavityGuid = guid;
    }
    return true;
}

struct VtfView {
    std::uint32_t width = 0, height = 0, mipCount = 0, format = 0;
    std::size_t dataOffset = 0;
};

bool parseVtfView(const std::vector<std::uint8_t>& vtf, VtfView& view) {
    if (vtf.size() < 0x58 || std::memcmp(vtf.data(), "VTF\0", 4) != 0) return false;
    view.width = u16(vtf.data() + 0x10);
    view.height = u16(vtf.data() + 0x12);
    view.mipCount = vtf[0x38];
    view.format = u32(vtf.data() + 0x34);
    view.dataOffset = u32(vtf.data() + 0x54);
    return view.width && view.height && view.mipCount && view.mipCount <= 32 && view.dataOffset >= 0x58 &&
           view.dataOffset <= vtf.size();
}

// Bytes of one mip level for the formats the converter emits, 0 when unsupported.
std::size_t vtfMipBytes(std::uint32_t format, std::uint32_t w, std::uint32_t h) {
    const std::size_t blocks = static_cast<std::size_t>((w + 3) / 4) * ((h + 3) / 4);
    switch (format) {
        case 0: return static_cast<std::size_t>(w) * h * 4;
        case 13: case 35: return blocks * 8;
        case 14: case 15: case 34: return blocks * 16;
        default: return 0;
    }
}

// Decodes mip `mip` (0 = largest) to RGBA8. Mips are stored smallest first.
bool decodeVtfMip(const std::vector<std::uint8_t>& vtf, const VtfView& view, std::uint32_t mip,
                  std::vector<std::uint8_t>& rgba, std::uint32_t& w, std::uint32_t& h) {
    if (mip >= view.mipCount) return false;
    std::size_t offset = view.dataOffset;
    for (std::uint32_t m = view.mipCount; m-- > mip + 1;) {
        const std::size_t bytes = vtfMipBytes(view.format, std::max(1u, view.width >> m), std::max(1u, view.height >> m));
        if (!bytes) return false;
        offset += bytes;
    }
    w = std::max(1u, view.width >> mip);
    h = std::max(1u, view.height >> mip);
    const std::size_t bytes = vtfMipBytes(view.format, w, h);
    if (!bytes || offset > vtf.size() || bytes > vtf.size() - offset) return false;
    rgba.assign(static_cast<std::size_t>(w) * h * 4, 255);
    const std::uint8_t* src = vtf.data() + offset;
    if (view.format == 0) {
        std::memcpy(rgba.data(), src, bytes);
        return true;
    }
    const std::size_t blockBytes = (view.format == 13 || view.format == 35) ? 8 : 16;
    const std::uint32_t blocksX = (w + 3) / 4, blocksY = (h + 3) / 4;
    std::array<std::uint8_t, 64> block{};
    std::array<std::uint8_t, 32> rg{};
    std::array<std::uint8_t, 16> r{};
    for (std::uint32_t by = 0; by < blocksY; ++by) {
        for (std::uint32_t bx = 0; bx < blocksX; ++bx) {
            const std::uint8_t* b = src + (static_cast<std::size_t>(by) * blocksX + bx) * blockBytes;
            if (view.format == 35) bcdec_bc4(b, r.data(), 4, 0);
            else if (view.format == 34) bcdec_bc5(b, rg.data(), 8, 0);
            else if (view.format == 13) bcdec_bc1(b, block.data(), 16);
            else if (view.format == 14) bcdec_bc2(b, block.data(), 16);
            else bcdec_bc3(b, block.data(), 16);
            for (std::uint32_t py = 0; py < 4 && by * 4 + py < h; ++py) {
                for (std::uint32_t px = 0; px < 4 && bx * 4 + px < w; ++px) {
                    const std::size_t local = static_cast<std::size_t>(py) * 4 + px;
                    std::uint8_t* dst = rgba.data() + (static_cast<std::size_t>(by * 4 + py) * w + bx * 4 + px) * 4;
                    if (view.format == 35) { dst[0] = dst[1] = dst[2] = r[local]; dst[3] = 255; }
                    else if (view.format == 34) { dst[0] = rg[local * 2]; dst[1] = rg[local * 2 + 1]; dst[2] = 0; dst[3] = 255; }
                    else std::memcpy(dst, block.data() + local * 4, 4);
                }
            }
        }
    }
    return true;
}

// albedo: converted albedo VTF (replaced by the RGBA8 merge); opacity: converted opacity map VTF (red = opacity).
bool mergeOpacityVtf(std::vector<std::uint8_t>& albedo, const std::vector<std::uint8_t>& opacity, std::string& error) {
    VtfView av, ov;
    if (!parseVtfView(albedo, av) || !parseVtfView(opacity, ov)) { error = "invalid VTF for opacity merge"; return false; }
    if (!vtfMipBytes(av.format, av.width, av.height) || !vtfMipBytes(ov.format, ov.width, ov.height)) {
        error = "opacity merge: unsupported VTF format " + std::to_string(av.format) + "/" + std::to_string(ov.format);
        return false;
    }
    const bool albedoHasAlpha = av.format == 0 || av.format == 14 || av.format == 15;
    std::uint64_t outputSize = 0x58;
    for (std::uint32_t m = av.mipCount; m-- > 0;)
        outputSize += static_cast<std::uint64_t>(std::max(1u, av.width >> m)) * std::max(1u, av.height >> m) * 4u;
    if (outputSize > (1ull << 31)) { error = "opacity merge: output too large"; return false; }
    std::vector<std::uint8_t> merged(static_cast<std::size_t>(outputSize), 0);
    std::memcpy(merged.data(), albedo.data(), 0x58);
    putI32(merged.data() + 0x34, 0);
    put32(merged.data() + 0x54, 0x58);
    std::size_t output = 0x58;
    std::vector<std::uint8_t> a, o;
    for (std::uint32_t m = av.mipCount; m-- > 0;) {
        std::uint32_t aw = 0, ah = 0, ow = 0, oh = 0;
        if (!decodeVtfMip(albedo, av, m, a, aw, ah)) { error = "opacity merge: albedo mip decode failed"; return false; }
        // Opacity mip with the same (or the nearest larger) size as the albedo mip.
        std::uint32_t om = 0;
        while (om + 1 < ov.mipCount && std::max(1u, ov.width >> (om + 1)) >= aw && std::max(1u, ov.height >> (om + 1)) >= ah) ++om;
        if (!decodeVtfMip(opacity, ov, om, o, ow, oh)) { error = "opacity merge: opacity mip decode failed"; return false; }
        for (std::uint32_t y = 0; y < ah; ++y) {
            const std::uint32_t oy = std::min(oh - 1, static_cast<std::uint32_t>((static_cast<std::uint64_t>(y) * oh) / ah));
            for (std::uint32_t x = 0; x < aw; ++x) {
                const std::uint32_t ox = std::min(ow - 1, static_cast<std::uint32_t>((static_cast<std::uint64_t>(x) * ow) / aw));
                const std::uint8_t* src = a.data() + (static_cast<std::size_t>(y) * aw + x) * 4;
                const std::uint8_t opa = o[(static_cast<std::size_t>(oy) * ow + ox) * 4];
                std::uint8_t* dst = merged.data() + output + (static_cast<std::size_t>(y) * aw + x) * 4;
                dst[0] = src[0]; dst[1] = src[1]; dst[2] = src[2];
                dst[3] = static_cast<std::uint8_t>((albedoHasAlpha ? src[3] * opa + 127 : 255u * opa + 127) / 255u);
            }
        }
        output += static_cast<std::size_t>(aw) * ah * 4;
    }
    albedo = std::move(merged);
    return true;
}

// R2 foliage (shader sets with Cav and Cut and no Vcolt: grass, ground plants, bushes, leaf cards) carries a cavity map in
// slot 12 (a tuft bake: dark roots, light tips; every foliage material of the 20 maps that has Cut also has Cav, and the grass
// materials of different maps share one cavity texture). R2 also draws the cut-out with alpha-to-coverage, which keeps the mean
// blade coverage at every mip level. R1 has neither: its alpha test (0.7) loses more blades with each mip (mp_glitch
// glitch_amber_grass_01: 28 % of the texels pass at mip 0, 9 % at mip 4, so distant lawn is sparse pale speckle), the unoccluded
// tufts light up 1.5 to 3 times brighter than R2's (grass pixels conv/R2 luminance on mp_glitch 1.78, mp_homestead 1.54), and the
// cube reflection adds a pale blue sheen (homestead grass B/G 1.30x R2). The bake multiplies albedo by cavity^k and rebuilds the
// mip chain with premultiplied box filtering and an alpha gain that keeps the share of texels at or above the alpha-test
// reference constant; ConvertMaterial also drops the env reflection of these materials. Output is RGBA8 (same header as the
// albedo, flags kept). k is a calibration, not an R2 constant: mp_glitch grass wants a multiplier of about 0.55 (k 1.0 gives
// 1.10, k 0.5 gives 1.21 with the env sheen), mp_homestead about 0.73 (k 0.5 without env gives 0.74, k 1.5 gives 0.38); the
// default sits between the two.
constexpr float kFoliageAlphaRef = 0.7f;

float foliageCavityExponent() {
    float k = 0.4f;
    if (const char* e = std::getenv("R2TEX_FOLIAGE_CAV")) k = std::clamp(static_cast<float>(std::atof(e)), 0.0f, 4.0f);
    return k;
}

// albedo: converted albedo VTF (replaced); opacity: optional converted opacity map (red); cavity: converted cavity map (red).
bool buildFoliageVtf(std::vector<std::uint8_t>& albedo, const std::vector<std::uint8_t>* opacity,
                     const std::vector<std::uint8_t>& cavity, std::string& error) {
    VtfView av, cv, ov;
    if (!parseVtfView(albedo, av) || !parseVtfView(cavity, cv) || (opacity && !parseVtfView(*opacity, ov))) {
        error = "invalid VTF for foliage bake";
        return false;
    }
    std::vector<std::uint8_t> a, c, o;
    std::uint32_t aw = 0, ah = 0, cw = 0, ch = 0, ow = 0, oh = 0;
    if (!decodeVtfMip(albedo, av, 0, a, aw, ah) || !decodeVtfMip(cavity, cv, 0, c, cw, ch) ||
        (opacity && !decodeVtfMip(*opacity, ov, 0, o, ow, oh))) {
        error = "foliage bake: mip decode failed";
        return false;
    }
    const bool albedoHasAlpha = av.format == 0 || av.format == 14 || av.format == 15;
    const float k = foliageCavityExponent();
    std::array<float, 256> gain{};
    for (int i = 0; i < 256; ++i) gain[static_cast<std::size_t>(i)] = k == 0.0f ? 1.0f : std::pow(i / 255.0f, k);

    struct Level { std::uint32_t w = 0, h = 0; std::vector<float> px; };  // rgb 0..255, alpha 0..1
    std::vector<Level> chain(1);
    chain[0].w = aw; chain[0].h = ah;
    chain[0].px.resize(static_cast<std::size_t>(aw) * ah * 4);
    for (std::uint32_t y = 0; y < ah; ++y) {
        const std::uint32_t cy = std::min(ch - 1, static_cast<std::uint32_t>((static_cast<std::uint64_t>(y) * ch) / ah));
        const std::uint32_t oy = opacity ? std::min(oh - 1, static_cast<std::uint32_t>((static_cast<std::uint64_t>(y) * oh) / ah)) : 0;
        for (std::uint32_t x = 0; x < aw; ++x) {
            const std::uint32_t cx = std::min(cw - 1, static_cast<std::uint32_t>((static_cast<std::uint64_t>(x) * cw) / aw));
            const std::uint8_t* src = a.data() + (static_cast<std::size_t>(y) * aw + x) * 4;
            const float g = gain[c[(static_cast<std::size_t>(cy) * cw + cx) * 4]];
            float alpha = albedoHasAlpha ? src[3] / 255.0f : 1.0f;
            if (opacity) {
                const std::uint32_t ox = std::min(ow - 1, static_cast<std::uint32_t>((static_cast<std::uint64_t>(x) * ow) / aw));
                alpha *= o[(static_cast<std::size_t>(oy) * ow + ox) * 4] / 255.0f;
            }
            float* dst = &chain[0].px[(static_cast<std::size_t>(y) * aw + x) * 4];
            dst[0] = src[0] * g; dst[1] = src[1] * g; dst[2] = src[2] * g; dst[3] = alpha;
        }
    }
    auto coverage = [](const std::vector<float>& px, float gainScale) {
        std::size_t pass = 0;
        for (std::size_t i = 3; i < px.size(); i += 4) pass += std::min(1.0f, px[i] * gainScale) >= kFoliageAlphaRef;
        return static_cast<double>(pass) / std::max<std::size_t>(1, px.size() / 4);
    };
    const double target = coverage(chain[0].px, 1.0f);
    for (std::uint32_t m = 1; m < av.mipCount; ++m) {
        const Level& prev = chain.back();
        Level next;
        next.w = std::max(1u, prev.w / 2); next.h = std::max(1u, prev.h / 2);
        next.px.resize(static_cast<std::size_t>(next.w) * next.h * 4);
        for (std::uint32_t y = 0; y < next.h; ++y)
            for (std::uint32_t x = 0; x < next.w; ++x) {
                double sum[3] = {0, 0, 0}, plain[3] = {0, 0, 0}, alphaSum = 0;
                for (std::uint32_t dy = 0; dy < 2; ++dy)
                    for (std::uint32_t dx = 0; dx < 2; ++dx) {
                        const std::uint32_t sx = std::min(prev.w - 1, x * 2 + dx), sy = std::min(prev.h - 1, y * 2 + dy);
                        const float* s = &prev.px[(static_cast<std::size_t>(sy) * prev.w + sx) * 4];
                        for (int i = 0; i < 3; ++i) { sum[i] += s[i] * s[3]; plain[i] += s[i]; }
                        alphaSum += s[3];
                    }
                float* d = &next.px[(static_cast<std::size_t>(y) * next.w + x) * 4];
                for (int i = 0; i < 3; ++i)
                    d[i] = static_cast<float>(alphaSum > 1e-4 ? sum[i] / alphaSum : plain[i] / 4.0);
                d[3] = static_cast<float>(alphaSum / 4.0);
            }
        if (target > 0.0) {
            float lo = 0.5f, hi = 8.0f;
            for (int i = 0; i < 24; ++i) {
                const float mid = 0.5f * (lo + hi);
                if (coverage(next.px, mid) < target) lo = mid; else hi = mid;
            }
            for (std::size_t i = 3; i < next.px.size(); i += 4) next.px[i] = std::min(1.0f, next.px[i] * hi);
        }
        chain.push_back(std::move(next));
    }
    std::uint64_t outputSize = 0x58;
    for (const Level& level : chain) outputSize += static_cast<std::uint64_t>(level.w) * level.h * 4u;
    if (outputSize > (1ull << 31)) { error = "foliage bake: output too large"; return false; }
    std::vector<std::uint8_t> baked(static_cast<std::size_t>(outputSize), 0);
    std::memcpy(baked.data(), albedo.data(), 0x58);
    putI32(baked.data() + 0x34, 0);
    put32(baked.data() + 0x54, 0x58);
    baked[0x38] = static_cast<std::uint8_t>(chain.size());
    std::size_t at = 0x58;
    for (std::size_t m = chain.size(); m-- > 0;) {
        const Level& level = chain[m];
        for (std::size_t i = 0; i < level.px.size(); ++i) {
            const float v = i % 4 == 3 ? level.px[i] * 255.0f : level.px[i];
            baked[at + i] = static_cast<std::uint8_t>(std::clamp(v + 0.5f, 0.0f, 255.0f));
        }
        at += level.px.size();
    }
    albedo = std::move(baked);
    return true;
}

// R1 renders large single-mip textures as garbage (the mp_glitch training_r2 sky vista, a 2048x2048 DXT1 with one mip,
// came out as rainbow arches; with a full chain the same texels render correctly). R2 stores such textures (skies, vistas)
// with only mip 0. Expand them to an RGBA8 texture with a complete box-filtered chain.
bool addMipChain(std::vector<std::uint8_t>& vtf, std::string_view textureName) {
    // Color textures only: normal, opacity, mask, gloss and specular maps keep their single mip (a box filter would
    // de-normalize or blur their channel packing).
    static const char* const kSkip[] = {"_nml", "_normal", "_bump", "_opa", "_msk", "_bm", "_gls", "_spc", "_exp", "_cav", "_ao"};
    {
        const std::string lowered = lowerAscii(std::string(textureName));
        for (const char* suffix : kSkip) {
            const std::size_t n = std::strlen(suffix);
            if (lowered.size() >= n && lowered.compare(lowered.size() - n, n, suffix) == 0) return true;
        }
    }
    VtfView view;
    // A chain cut off at the small end (the 1,028 R2 textures stored with fewer mips than log2(size)+1: 2048 px _ilm glow maps with 4
    // mips) breaks in R1 the same way a single-mip texture does: mp_complex3 stackable_cages01 (_ilm, 2048 px, 4 mips) lit every crate
    // face lavender-white at any distance while R2 shows only the green LED dots; a complete chain (or an opaque black mask) removes it.
    if (!parseVtfView(vtf, view) || std::max(view.width, view.height) < 16) return true;
    {
        std::uint32_t fullMips = 1;
        for (std::uint32_t size = std::max(view.width, view.height); size > 1; size >>= 1) ++fullMips;
        if (view.mipCount >= fullMips) return true;
    }
    if (view.format != 0 && view.format != 13 && view.format != 14 && view.format != 15) return true;
    if (u16(vtf.data() + 0x18) != 1 || (u32(vtf.data() + 0x14) & (0x100u | 0x4000u)) != 0) return true;  // frames, NOMIP, ENVMAP
    std::vector<std::uint8_t> level;
    std::uint32_t w = 0, h = 0;
    if (!decodeVtfMip(vtf, view, 0, level, w, h)) return true;
    std::vector<std::vector<std::uint8_t>> chain;
    std::vector<std::pair<std::uint32_t, std::uint32_t>> dims;
    chain.push_back(std::move(level)); dims.emplace_back(w, h);
    while (dims.back().first > 1 || dims.back().second > 1) {
        const auto [pw, ph] = dims.back();
        const std::uint32_t nw = std::max(1u, pw / 2), nh = std::max(1u, ph / 2);
        std::vector<std::uint8_t> next(static_cast<std::size_t>(nw) * nh * 4);
        const auto& prev = chain.back();
        for (std::uint32_t y = 0; y < nh; ++y)
            for (std::uint32_t x = 0; x < nw; ++x) {
                const std::uint32_t x0 = std::min(pw - 1, x * 2), x1 = std::min(pw - 1, x * 2 + 1);
                const std::uint32_t y0 = std::min(ph - 1, y * 2), y1 = std::min(ph - 1, y * 2 + 1);
                for (int c = 0; c < 4; ++c) {
                    const unsigned sum = prev[(static_cast<std::size_t>(y0) * pw + x0) * 4 + c] +
                                         prev[(static_cast<std::size_t>(y0) * pw + x1) * 4 + c] +
                                         prev[(static_cast<std::size_t>(y1) * pw + x0) * 4 + c] +
                                         prev[(static_cast<std::size_t>(y1) * pw + x1) * 4 + c];
                    next[(static_cast<std::size_t>(y) * nw + x) * 4 + c] = static_cast<std::uint8_t>((sum + 2) / 4);
                }
            }
        chain.push_back(std::move(next)); dims.emplace_back(nw, nh);
    }
    if (view.format == 13) {
        // DXT1 source: keep the original top mip bytes, re-encode the smaller mips as DXT1 (11x smaller than RGBA8).
        const std::size_t topBytes = vtfMipBytes(13, w, h);
        std::size_t total = 0x58;
        for (std::size_t m = 0; m < chain.size(); ++m)
            total += m == 0 ? topBytes : vtfMipBytes(13, dims[m].first, dims[m].second);
        std::vector<std::uint8_t> out(total, 0);
        std::memcpy(out.data(), vtf.data(), 0x58);
        out[0x38] = static_cast<std::uint8_t>(chain.size());
        put32(out.data() + 0x54, 0x58);
        std::size_t at = 0x58;
        for (std::size_t m = chain.size(); m-- > 0;) {
            const std::uint32_t mw = dims[m].first, mh = dims[m].second;
            if (m == 0) {
                std::memcpy(out.data() + at, vtf.data() + view.dataOffset, topBytes);
                at += topBytes;
                continue;
            }
            const std::uint32_t bx = (mw + 3) / 4, by = (mh + 3) / 4;
            for (std::uint32_t y = 0; y < by; ++y)
                for (std::uint32_t x = 0; x < bx; ++x) {
                    std::uint8_t block[16][3];
                    for (int py = 0; py < 4; ++py)
                        for (int px = 0; px < 4; ++px) {
                            const std::uint32_t sx = std::min(mw - 1, x * 4 + px), sy = std::min(mh - 1, y * 4 + py);
                            const std::uint8_t* s = &chain[m][(static_cast<std::size_t>(sy) * mw + sx) * 4];
                            block[py * 4 + px][0] = s[0]; block[py * 4 + px][1] = s[1]; block[py * 4 + px][2] = s[2];
                        }
                    encodeBc1Block(block, out.data() + at + (static_cast<std::size_t>(y) * bx + x) * 8);
                }
            at += static_cast<std::size_t>(bx) * by * 8;
        }
        vtf = std::move(out);
        return true;
    }
    std::size_t total = 0x58;
    for (const auto& m : chain) total += m.size();
    std::vector<std::uint8_t> out(total, 0);
    std::memcpy(out.data(), vtf.data(), 0x58);
    putI32(out.data() + 0x34, 0);
    out[0x38] = static_cast<std::uint8_t>(chain.size());
    put32(out.data() + 0x54, 0x58);
    std::size_t at = 0x58;
    for (std::size_t i = chain.size(); i-- > 0;) {
        std::memcpy(out.data() + at, chain[i].data(), chain[i].size());
        at += chain[i].size();
    }
    vtf = std::move(out);
    return true;
}

// R2 normal maps (material slots 1 and 24) store x/y slopes, as BC5 RG or in the R1 DXT1 layout: n = normalize(float3(rg * 2.867661
// - 1.439453, 1)) (the blue channel is ignored). R1's pixel shaders read a unit normal from RGB (stock R1 *_nml are DXT1 RGB with VTF
// flag 0x80). A BC5 source arrives in R1 with B = 0 and lights every bumped surface wrong (measured on mp_glitch: the whole world
// shaded dark and blue; the repacked texture lights it neutrally). Every mip is re-encoded as unit-normal DXT1, green not flipped
// (R1 and R2 normals of the same stock asset correlate +0.95 on both channels).
constexpr const char* kNormalMapPrefix = "r2tex/nrm/";

std::string normalMapName(const std::string& textureName) {
    return std::string(kNormalMapPrefix) + cleanAssetName(textureName, true);
}

// Encodes 16 RGB texels (row-major 4x4) as one DXT1 four-colour block: principal axis fit, then nearest palette entry.
void encodeBc1Block(const std::uint8_t (&px)[16][3], std::uint8_t* out) {
    float mean[3] = {0, 0, 0};
    for (const auto& p : px) for (int c = 0; c < 3; ++c) mean[c] += p[c];
    for (float& m : mean) m /= 16.0f;
    float cov[3][3] = {};
    for (const auto& p : px) {
        const float d[3] = {p[0] - mean[0], p[1] - mean[1], p[2] - mean[2]};
        for (int a = 0; a < 3; ++a) for (int b = 0; b < 3; ++b) cov[a][b] += d[a] * d[b];
    }
    float axis[3] = {cov[0][0] + 1e-3f, cov[1][1] + 1e-3f, cov[2][2] + 1e-3f};
    for (int it = 0; it < 6; ++it) {
        float next[3] = {};
        for (int a = 0; a < 3; ++a) for (int b = 0; b < 3; ++b) next[a] += cov[a][b] * axis[b];
        const float len = std::sqrt(next[0] * next[0] + next[1] * next[1] + next[2] * next[2]);
        if (len < 1e-6f) break;
        for (int a = 0; a < 3; ++a) axis[a] = next[a] / len;
    }
    float tmin = 0, tmax = 0;
    for (const auto& p : px) {
        const float t = (p[0] - mean[0]) * axis[0] + (p[1] - mean[1]) * axis[1] + (p[2] - mean[2]) * axis[2];
        tmin = std::min(tmin, t); tmax = std::max(tmax, t);
    }
    auto q565 = [](const float* c) {
        const int r = std::clamp(static_cast<int>(c[0] * 31.0f / 255.0f + 0.5f), 0, 31);
        const int g = std::clamp(static_cast<int>(c[1] * 63.0f / 255.0f + 0.5f), 0, 63);
        const int b = std::clamp(static_cast<int>(c[2] * 31.0f / 255.0f + 0.5f), 0, 31);
        return static_cast<std::uint16_t>((r << 11) | (g << 5) | b);
    };
    float hi[3], lo[3];
    for (int c = 0; c < 3; ++c) { hi[c] = mean[c] + axis[c] * tmax; lo[c] = mean[c] + axis[c] * tmin; }
    auto expand = [](std::uint16_t c, int* o) {
        const int r = (c >> 11) & 31, g = (c >> 5) & 63, b = c & 31;
        o[0] = (r << 3) | (r >> 2); o[1] = (g << 2) | (g >> 4); o[2] = (b << 3) | (b >> 2);
    };
    std::uint16_t c0 = 0, c1 = 0;
    std::uint32_t indices = 0, bestIndices = 0;
    std::uint16_t bestC0 = 0, bestC1 = 0;
    long bestError = std::numeric_limits<long>::max();
    // Pass 0 fits along the principal axis; passes 1 and 2 refit both endpoints by least squares to the previous assignment.
    for (int pass = 0; pass < 3; ++pass) {
        c0 = q565(hi); c1 = q565(lo);
        if (c0 < c1) std::swap(c0, c1);
        int pal[4][3];
        expand(c0, pal[0]); expand(c1, pal[1]);
        for (int c = 0; c < 3; ++c) { pal[2][c] = (2 * pal[0][c] + pal[1][c]) / 3; pal[3][c] = (pal[0][c] + 2 * pal[1][c]) / 3; }
        indices = 0;
        long error = 0;
        int index[16];
        for (int i = 0; i < 16; ++i) {
            int best = 0, bestDistance = std::numeric_limits<int>::max();
            if (c0 != c1) {
                for (int k = 0; k < 4; ++k) {
                    int distance = 0;
                    for (int c = 0; c < 3; ++c) { const int d = px[i][c] - pal[k][c]; distance += d * d; }
                    if (distance < bestDistance) { bestDistance = distance; best = k; }
                }
            } else {
                bestDistance = 0;
                for (int c = 0; c < 3; ++c) { const int d = px[i][c] - pal[0][c]; bestDistance += d * d; }
            }
            index[i] = best; error += bestDistance;
            indices |= static_cast<std::uint32_t>(best) << (2 * i);
        }
        if (error < bestError) { bestError = error; bestIndices = indices; bestC0 = c0; bestC1 = c1; }
        if (error == 0 || pass == 2) break;
        // Least squares: texel ~ a * E0 + (1 - a) * E1 with a = 1, 0, 2/3, 1/3 for indices 0, 1, 2, 3.
        float aa = 0, bb = 0, ab = 0, ya[3] = {}, yb[3] = {};
        static const float weight[4] = {1.0f, 0.0f, 2.0f / 3.0f, 1.0f / 3.0f};
        for (int i = 0; i < 16; ++i) {
            const float a = weight[index[i]], b = 1.0f - a;
            aa += a * a; bb += b * b; ab += a * b;
            for (int c = 0; c < 3; ++c) { ya[c] += a * px[i][c]; yb[c] += b * px[i][c]; }
        }
        const float det = aa * bb - ab * ab;
        if (std::fabs(det) < 1e-4f) break;
        for (int c = 0; c < 3; ++c) {
            hi[c] = std::clamp((ya[c] * bb - yb[c] * ab) / det, 0.0f, 255.0f);
            lo[c] = std::clamp((yb[c] * aa - ya[c] * ab) / det, 0.0f, 255.0f);
        }
    }
    out[0] = static_cast<std::uint8_t>(bestC0 & 255); out[1] = static_cast<std::uint8_t>(bestC0 >> 8);
    out[2] = static_cast<std::uint8_t>(bestC1 & 255); out[3] = static_cast<std::uint8_t>(bestC1 >> 8);
    for (int i = 0; i < 4; ++i) out[4 + i] = static_cast<std::uint8_t>(bestIndices >> (8 * i));
}

bool convertNormalVtf(std::vector<std::uint8_t>& vtf, std::string& error) {
    VtfView view;
    if (!parseVtfView(vtf, view) || u16(vtf.data() + 0x18) != 1) { error = "invalid source VTF for normal map"; return false; }
    if (view.format != 0 && view.format != 13 && view.format != 14 && view.format != 15 && view.format != 34) {
        error = "normal map: unsupported VTF format " + std::to_string(view.format);
        return false;
    }
    std::vector<std::vector<std::uint8_t>> mips(view.mipCount);
    std::vector<std::uint8_t> level;
    for (std::uint32_t m = 0; m < view.mipCount; ++m) {
        std::uint32_t w = 0, h = 0;
        if (!decodeVtfMip(vtf, view, m, level, w, h)) { error = "normal map: mip decode failed"; return false; }
        std::vector<std::uint8_t> rgb(static_cast<std::size_t>(w) * h * 3);
        for (std::size_t i = 0, n = static_cast<std::size_t>(w) * h; i < n; ++i) {
            const float sx = level[i * 4] * (2.867661f / 255.0f) - 1.439453f;
            const float sy = level[i * 4 + 1] * (2.867661f / 255.0f) - 1.439453f;
            const float inv = 1.0f / std::sqrt(sx * sx + sy * sy + 1.0f);
            rgb[i * 3] = static_cast<std::uint8_t>(std::clamp((sx * inv * 0.5f + 0.5f) * 255.0f + 0.5f, 0.0f, 255.0f));
            rgb[i * 3 + 1] = static_cast<std::uint8_t>(std::clamp((sy * inv * 0.5f + 0.5f) * 255.0f + 0.5f, 0.0f, 255.0f));
            rgb[i * 3 + 2] = static_cast<std::uint8_t>(std::clamp((inv * 0.5f + 0.5f) * 255.0f + 0.5f, 0.0f, 255.0f));
        }
        const std::uint32_t bx = (w + 3) / 4, by = (h + 3) / 4;
        mips[m].resize(static_cast<std::size_t>(bx) * by * 8);
        for (std::uint32_t y = 0; y < by; ++y)
            for (std::uint32_t x = 0; x < bx; ++x) {
                std::uint8_t block[16][3];
                for (std::uint32_t py = 0; py < 4; ++py)
                    for (std::uint32_t px = 0; px < 4; ++px) {
                        const std::uint32_t sx = std::min(w - 1, x * 4 + px), sy = std::min(h - 1, y * 4 + py);
                        std::memcpy(block[py * 4 + px], &rgb[(static_cast<std::size_t>(sy) * w + sx) * 3], 3);
                    }
                encodeBc1Block(block, &mips[m][(static_cast<std::size_t>(y) * bx + x) * 8]);
            }
    }
    std::vector<std::uint8_t> out(vtf.begin(), vtf.begin() + view.dataOffset);
    put32(out.data() + 0x14, (u32(out.data() + 0x14) | 0x80u) & ~0x80000u);   // NORMAL, not sRGB
    putI32(out.data() + 0x34, 13);
    for (std::uint32_t m = view.mipCount; m-- > 0;) out.insert(out.end(), mips[m].begin(), mips[m].end());
    vtf = std::move(out);
    return true;
}

