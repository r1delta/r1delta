bool FamilyOfTexture(std::string_view name, std::uint32_t& family) {
    try {
        const auto db = getDatabase();
        if (!db) return false;
        const std::string cleaned = cleanAssetName(name, true);
        if (!validAssetName(cleaned)) return false;
        std::uint64_t guid = 0;
        if (cleaned.rfind(kOpaqueAlbedoPrefix, 0) == 0) {
            const std::string original = cleaned.substr(std::strlen(kOpaqueAlbedoPrefix));
            if (!validAssetName(original)) return false;
            guid = textureGuid(original);
        } else if (cleaned.rfind(kNormalMapPrefix, 0) == 0) {
            const std::string original = cleaned.substr(std::strlen(kNormalMapPrefix));
            if (!validAssetName(original)) return false;
            guid = textureGuid(original);
        } else if (cleaned.rfind(kGlowRampPrefix, 0) == 0) {
            const std::string original = cleaned.substr(std::strlen(kGlowRampPrefix));
            if (!validAssetName(original)) return false;
            guid = textureGuid(original);
        } else if (cleaned.rfind(kSpecGlossPrefix, 0) == 0) {
            std::uint64_t spc = 0, gls = 0;
            if (!parseSpecGlossName(cleaned, spc, gls)) return false;
            guid = spc;
        } else if (cleaned.rfind(kOpacityMergePrefix, 0) == 0) {
            std::uint64_t opacityGuid = 0;
            if (!parseOpacityMergeName(cleaned, guid, opacityGuid)) return false;
        } else if (cleaned.rfind(kUberPackPrefix, 0) == 0 || cleaned.rfind(kUberPackLayeredPrefix, 0) == 0) {
            std::uint64_t mask = 0, ao = 0, cavity = 0;
            if (!parseUberPackName(cleaned, mask, ao, cavity)) return false;
            guid = mask ? mask : (ao ? ao : cavity);
        } else if (cleaned.rfind("r2tex/layer_masks/", 0) == 0) {
            const std::string hex = cleaned.substr(std::strlen("r2tex/layer_masks/"), 16);
            char* end = nullptr;
            guid = std::strtoull(hex.c_str(), &end, 16);
            if (hex.size() != 16 || end != hex.c_str() + 16) return false;
        } else {
            guid = textureGuid(cleaned);
        }
        const AssetRecord* record = findRecord(*db, guid, kTxtr);
        if (!record) record = findTextureByName(*db, cleaned);
        if (record) {
            family = db->paks[record->pakIndex].family;
            return true;
        }
    } catch (...) {
    }
    return false;
}

