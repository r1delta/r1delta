bool resolvePageAtVersion(const Family& family, const PakData& owner, std::uint32_t page,
                          PageLocation& location) {
    if (page >= family.pages.size()) return false;
    std::size_t ownerIndex = family.paks.size();
    for (std::size_t i = 0; i < family.paks.size(); ++i) {
        if (family.paks[i].get() == &owner) { ownerIndex = i; break; }
    }
    if (ownerIndex == family.paks.size()) return false;
    for (std::size_t i = 0; i <= ownerIndex; ++i) {
        const PakData& pak = *family.paks[i];
        if (page >= pak.pageOffsets.size() || pak.pageOffsets[page] == std::numeric_limits<std::size_t>::max()) continue;
        location = {&pak, pak.pageOffsets[page], static_cast<std::size_t>(pak.pageSizes[page])};
    }
    return location.pak != nullptr;
}

bool readPageRange(const Family& family, const PakData& owner, PagePtr ptr, std::size_t length,
                   std::vector<std::uint8_t>& out, std::string& error) {
    if (ptr.index == 0xffffffffu || ptr.index >= family.pages.size()) { error = "invalid page index"; return false; }
    {
        // Which paks hold the pages of the range is known from the layout alone; decode the missing ones together.
        std::vector<const PakData*> need;
        std::size_t remaining = length;
        std::uint32_t page = ptr.index;
        std::size_t pageOffset = ptr.offset;
        while (remaining) {
            PageLocation loc;
            if (!resolvePageAtVersion(family, owner, page, loc) || pageOffset > loc.size) break;   // reported below
            if (!loc.pak->loaded.load(std::memory_order_acquire) && std::find(need.begin(), need.end(), loc.pak) == need.end())
                need.push_back(loc.pak);
            const std::size_t available = loc.size - pageOffset;
            if (!available) break;
            remaining -= std::min(available, remaining);
            pageOffset = 0;
            if (remaining) {
                if (page + 1 >= family.pages.size()) break;
                ++page;
            }
        }
        if (!need.empty() && !ensurePaksLoaded(family, need, error)) return false;
    }
    out.resize(length);
    std::size_t remaining = length, dest = 0;
    std::uint32_t page = ptr.index;
    std::size_t pageOffset = ptr.offset;
    while (remaining) {
        PageLocation loc;
        if (!resolvePageAtVersion(family, owner, page, loc) || pageOffset > loc.size) {
            error = "missing page in patch chain"; return false;
        }
        const std::size_t available = loc.size - pageOffset;
        if (!available) { error = "empty page in patch chain"; return false; }
        const std::size_t chunk = std::min(available, remaining);
        std::memcpy(out.data() + dest, loc.pak->bytes.data() + loc.offset + pageOffset, chunk);
        dest += chunk;
        remaining -= chunk;
        pageOffset = 0;
        if (remaining) {
            if (page + 1 >= family.pages.size()) { error = "asset range past final page"; return false; }
            ++page;
        }
    }
    return true;
}

bool readCString(const Family& family, const PakData& owner, PagePtr ptr, std::string& value) {
    if (ptr.index == 0xffffffffu || ptr.index >= family.pages.size()) return false;
    PageLocation loc;
    if (!resolvePageAtVersion(family, owner, ptr.index, loc) || ptr.offset >= loc.size) return false;
    if (!loc.pak->loaded.load(std::memory_order_acquire)) {
        std::string ignored;
        if (!ensurePaksLoaded(family, {loc.pak}, ignored)) return false;
    }
    const char* data = reinterpret_cast<const char*>(loc.pak->bytes.data() + loc.offset + ptr.offset);
    const std::size_t maximum = loc.size - ptr.offset;
    const void* nul = std::memchr(data, 0, maximum);
    if (!nul) return false;
    const auto length = static_cast<const char*>(nul) - data;
    if (length <= 0 || length > 4096) return false;
    value.assign(data, static_cast<std::size_t>(length));
    return true;
}


bool readPageHeader(const Family& family, const PakData& owner, PagePtr ptr, std::size_t length,
                    std::vector<std::uint8_t>& header) {
    std::string ignored;
    return readPageRange(family, owner, ptr, length, header, ignored);
}


std::uint32_t typeFromFourcc(const char* s) {
    return static_cast<std::uint32_t>(static_cast<unsigned char>(s[0])) |
        (static_cast<std::uint32_t>(static_cast<unsigned char>(s[1])) << 8) |
        (static_cast<std::uint32_t>(static_cast<unsigned char>(s[2])) << 16) |
        (static_cast<std::uint32_t>(static_cast<unsigned char>(s[3])) << 24);
}

struct AssetKey {
    std::uint64_t guid;
    std::uint32_t type;
    bool operator==(const AssetKey& o) const noexcept { return guid == o.guid && type == o.type; }
};
struct AssetKeyHash {
    std::size_t operator()(const AssetKey& k) const noexcept {
        std::uint64_t x = k.guid ^ (static_cast<std::uint64_t>(k.type) << 32);
        x ^= x >> 33; x *= 0xff51afd7ed558ccdull; x ^= x >> 33;
        return static_cast<std::size_t>(x);
    }
};
struct AssetRecord {
    std::uint64_t guid = 0;
    std::uint32_t type = 0;
    std::uint32_t pakIndex = 0;
    std::uint32_t assetIndex = 0;
    PagePtr head{};
    PagePtr data{};
    std::int64_t starpakOffset = -1;
    std::uint32_t version = 0;
    std::uint32_t headerSize = 0;
    std::string name;
};

bool readAssetEnt(const PakData& pak, std::uint32_t index, AssetEnt& asset) {
    if (index >= pak.header.numAssets) return false;
    const std::size_t off = pak.assetTableOffset + static_cast<std::size_t>(index) * sizeof(AssetEnt);
    if (off > pak.bytes.size() || sizeof(AssetEnt) > pak.bytes.size() - off) return false;
    std::memcpy(&asset, pak.bytes.data() + off, sizeof(asset));
    return true;
}

bool readHeaderAndName(const Family& family, const PakData& owner, const AssetEnt& asset,
                       std::vector<std::uint8_t>& header, std::string& name) {
    std::size_t required = asset.type == kTxtr ? 0x38u : asset.type == kMatl ? 0xd0u : 0x58u;
    if (asset.headerSize && asset.headerSize < required) return false;
    if (!readPageHeader(family, owner, asset.head, required, header)) return false;
    std::size_t ptrOffset = asset.type == kMatl ? 0x18u : asset.type == kTxtr || asset.type == kShds ? 0x08u : required;
    if (ptrOffset + sizeof(PagePtr) > header.size()) return false;
    PagePtr namePtr{};
    std::memcpy(&namePtr, header.data() + ptrOffset, sizeof(PagePtr));
    if (!readCString(family, owner, namePtr, name)) return false;
    if (!validUtf8(name)) return false;
    for (unsigned char c : name) if (c < 0x20u || c == 0x7fu) return false;
    return true;
}

bool writeString(std::ofstream& out, const std::string& s) {
    if (s.size() > 0xffffffffu) return false;
    const std::uint32_t n = static_cast<std::uint32_t>(s.size());
    out.write(reinterpret_cast<const char*>(&n), sizeof(n));
    if (n) out.write(s.data(), n);
    return static_cast<bool>(out);
}
bool readString(std::ifstream& in, std::string& s, std::uint32_t max = 1u << 20) {
    std::uint32_t n = 0;
    if (!in.read(reinterpret_cast<char*>(&n), sizeof(n)) || n > max) return false;
    s.resize(n);
    return !n || static_cast<bool>(in.read(s.data(), n));
}

template<class T> bool writePod(std::ofstream& out, const T& v) {
    out.write(reinterpret_cast<const char*>(&v), sizeof(v)); return static_cast<bool>(out);
}
template<class T> bool readPod(std::ifstream& in, T& v) {
    return static_cast<bool>(in.read(reinterpret_cast<char*>(&v), sizeof(v)));
}

struct CacheEntry {
    std::shared_ptr<Family> family;
    std::list<std::uint32_t>::iterator age;
};
std::atomic<std::uint64_t> gFamilyLoadCount{0};
std::atomic<std::uint64_t> gFamilyLoadMicroseconds{0};

// Process-wide cap on pak loads running at once (read + RTech decode). Every getFamily caller always makes progress
// on its own thread and counts as one active load; helper threads are only started while the count is below the cap,
// and nothing ever blocks waiting for a slot, so concurrent families (provider workers, index scan threads) share the
// cap without deadlock or oversubscription.
std::atomic<unsigned> gPakLoadsActive{0};
// Set on the index scan threads: their pak decode helpers run below normal priority so a first-launch index build (a few seconds of
// every core) does not compete with the engine start-up and the main menu.
thread_local bool tLowPriorityLoad = false;
unsigned pakLoadLimit() {
    static const unsigned limit = [] {
        const unsigned hardware = std::thread::hardware_concurrency();
        return hardware > 3u ? hardware - 2u : 1u;
    }();
    return limit;
}

// R2TEX_LAZY_PAKS=0 decodes every pak of a family when the family is first used (the behavior before the pak layout was persisted in
// the index); the default decodes only the paks that own a page that is read.
bool lazyPaksEnabled() {
    static const bool enabled = [] {
        const char* value = std::getenv("R2TEX_LAZY_PAKS");
        return !(value && value[0] == '0');
    }();
    return enabled;
}

// Runs fn(slot) for every slot in `order` (claimed in that order) on the calling thread plus helper threads while the process-wide
// cap allows. An exception thrown by fn is rethrown here after every claimed slot finished.
template<class Fn>
void runPakLoads(const std::vector<std::size_t>& order, Fn&& fn) {
    const std::size_t count = order.size();
    std::atomic<std::size_t> next{0};
    std::exception_ptr failure;
    std::mutex failureMutex;
    // Claims and runs one slot; false once every slot is claimed.
    const auto loadNext = [&]() {
        const std::size_t k = next.fetch_add(1, std::memory_order_relaxed);
        if (k >= count) return false;
        try {
            fn(order[k]);
        } catch (...) {
            std::lock_guard<std::mutex> lock(failureMutex);
            if (!failure) failure = std::current_exception();
        }
        return true;
    };
    std::vector<std::thread> helpers;
    const bool lowPriority = tLowPriorityLoad;
    gPakLoadsActive.fetch_add(1, std::memory_order_relaxed);   // the calling thread
    const auto spawnHelpers = [&]() {
        const unsigned limit = pakLoadLimit();
        while (helpers.size() + 1 < count && next.load(std::memory_order_relaxed) < count) {
            unsigned active = gPakLoadsActive.load(std::memory_order_relaxed);
            if (active >= limit) return;
            if (!gPakLoadsActive.compare_exchange_weak(active, active + 1, std::memory_order_relaxed)) continue;
            try {
                helpers.emplace_back([&, lowPriority]() {
                    if (lowPriority) SetThreadPriority(GetCurrentThread(), THREAD_PRIORITY_BELOW_NORMAL);
                    while (loadNext()) {}
                    gPakLoadsActive.fetch_sub(1, std::memory_order_relaxed);
                });
            } catch (...) {
                gPakLoadsActive.fetch_sub(1, std::memory_order_relaxed);
                return;
            }
        }
    };
    // The caller loads one at a time and re-checks for free slots between them.
    spawnHelpers();
    while (loadNext()) spawnHelpers();
    for (auto& helper : helpers) helper.join();
    gPakLoadsActive.fetch_sub(1, std::memory_order_relaxed);
    if (failure) std::rethrow_exception(failure);
}

// Loads the given paks (indices into `paks`) in full and returns the ones that loaded, in the order of `members`.
// A pak that fails to load is skipped. Largest paks are claimed first so the biggest decode starts immediately.
std::vector<std::shared_ptr<PakData>> loadPaksConcurrent(const std::vector<PakInfo>& paks, const std::vector<std::uint32_t>& members) {
    const std::size_t count = members.size();
    std::vector<std::shared_ptr<PakData>> loaded(count);
    std::vector<std::size_t> order(count);
    for (std::size_t i = 0; i < count; ++i) order[i] = i;
    std::stable_sort(order.begin(), order.end(), [&](std::size_t a, std::size_t b) {
        return paks[members[a]].fileSize > paks[members[b]].fileSize;
    });
    runPakLoads(order, [&](std::size_t slot) {
        auto pak = std::make_shared<PakData>();
        std::string why;
        if (loadPak(paks[members[slot]], members[slot], *pak, why)) loaded[slot] = std::move(pak);
    });
    std::vector<std::shared_ptr<PakData>> result;
    result.reserve(count);
    for (auto& pak : loaded) if (pak) result.push_back(std::move(pak));
    return result;
}

struct Database {
    fs::path installDir;
    fs::path pakDir;
    fs::path cacheFile;
    std::string installIdentity;
    std::vector<PakInfo> paks;
    std::vector<std::vector<std::uint32_t>> familyMembers;
    std::vector<std::string> familyNames;
    std::unordered_map<AssetKey, AssetRecord, AssetKeyHash> assets;
    std::mutex familyMutex;
    std::unordered_map<std::uint32_t, CacheEntry> families;
    std::list<std::uint32_t> lru;
    std::size_t familyBytes = 0;
    std::unordered_map<std::uint32_t, int> familyPins;       // family -> queued-work pin count (see pinFamily)
    std::unordered_map<std::uint32_t, int> loadingFamilies;  // family -> decodes running in it right now (family creation or lazy pak decode)
    std::vector<PakMeta> pakMeta;                            // per pak (index order): layout persisted in r2tex.index

    std::unordered_map<std::uint32_t, std::shared_ptr<std::mutex>> familyLoadLocks;
    // Lower-case, slash-normalized asset name -> guid, built on first use, for texture records whose guid is
    // not hash("texture/<name>.rpak") (the per-map overview images "overviews\<map>").
    std::once_flag textureNamesOnce;
    std::unordered_map<std::string, std::uint64_t> textureNames;

    // True while the family object is cached and nothing is decoding in it. With a persisted layout the object itself costs nothing,
    // paks decode lazily when a page they own is read; a family a worker is decoding into is "loading", not "resident".
    bool isFamilyResident(std::uint32_t id) {
        std::lock_guard<std::mutex> lock(familyMutex);
        return families.find(id) != families.end() && loadingFamilies.find(id) == loadingFamilies.end();
    }
    void beginLoading(std::uint32_t id) {
        std::lock_guard<std::mutex> lock(familyMutex);
        ++loadingFamilies[id];
    }
    void endLoading(std::uint32_t id) {
        std::lock_guard<std::mutex> lock(familyMutex);
        const auto it = loadingFamilies.find(id);
        if (it != loadingFamilies.end() && --it->second <= 0) loadingFamilies.erase(it);
    }
    // A lazy pak decode made `added` more bytes of the family resident.
    void addFamilyBytes(const Family& family, std::size_t added) {
        std::lock_guard<std::mutex> lock(familyMutex);
        family.bytes.fetch_add(added, std::memory_order_relaxed);
        const auto found = families.find(family.id);
        if (found == families.end() || found->second.family.get() != &family) return;   // already evicted: only the holder keeps it
        familyBytes += added;
        evictLocked(family.id);
    }

    // Families are built under a per-family lock (not familyMutex), so workers needing different families build them in parallel.
    // Builds (or returns the cached) family. With a persisted pak layout the family is created without decoding anything: a pak is
    // read and RTech-decoded the first time a page it owns is read (ensurePaksLoaded). `eager` (the index scan, or a pak without a
    // persisted layout) decodes every pak now and records its layout in pakMeta.
    std::shared_ptr<Family> getFamily(std::uint32_t id, std::string& error, bool eager = false) {
        std::shared_ptr<std::mutex> loadLock;
        {
            std::lock_guard<std::mutex> lock(familyMutex);
            auto found = families.find(id);
            if (found != families.end()) {
                lru.splice(lru.begin(), lru, found->second.age);
                return found->second.family;
            }
            if (id >= familyMembers.size()) { error = "invalid package family"; return {}; }
            auto& slot = familyLoadLocks[id];
            if (!slot) slot = std::make_shared<std::mutex>();
            loadLock = slot;
        }
        std::unique_lock<std::mutex> loading(*loadLock, std::defer_lock);
        {
            R2P_SCOPE_L("d.fam.wait", familyNames[id]);
            loading.lock();
        }
        {
            std::lock_guard<std::mutex> lock(familyMutex);
            auto found = families.find(id);
            if (found != families.end()) {
                lru.splice(lru.begin(), lru, found->second.age);
                return found->second.family;
            }
        }
        beginLoading(id);
        struct LoadingGuard {
            Database& db; std::uint32_t id;
            ~LoadingGuard() { db.endLoading(id); }
        } loadingGuard{*this, id};
        R2P_SCOPE_B(profileFamily, "d.fam.load", familyNames[id]);
        const auto familyLoadStart = std::chrono::steady_clock::now();
        auto family = std::make_shared<Family>();
        family->id = id;
        family->db = this;
        const auto& members = familyMembers[id];
        family->paks.resize(members.size());
        std::vector<std::size_t> eagerSlots;
        for (std::size_t slot = 0; slot < members.size(); ++slot) {
            const std::uint32_t pakIndex = members[slot];
            if (!eager && lazyPaksEnabled() && pakMeta[pakIndex].valid) {
                auto pak = std::make_shared<PakData>();
                pak->infoIndex = pakIndex;
                applyMeta(*pak, pakMeta[pakIndex]);
                family->paks[slot] = std::move(pak);
            } else {
                eagerSlots.push_back(slot);
            }
        }
        if (!eagerSlots.empty()) {
            std::vector<std::uint32_t> eagerMembers;
            eagerMembers.reserve(eagerSlots.size());
            for (const std::size_t slot : eagerSlots) eagerMembers.push_back(members[slot]);
            for (auto& loaded : loadPaksConcurrent(paks, eagerMembers)) {
                for (const std::size_t slot : eagerSlots) {
                    if (members[slot] != loaded->infoIndex) continue;
                    pakMeta[loaded->infoIndex] = metaOf(*loaded);
                    family->paks[slot] = std::move(loaded);
                    break;
                }
            }
        }
        family->paks.erase(std::remove(family->paks.begin(), family->paks.end(), std::shared_ptr<PakData>()), family->paks.end());
        std::uint32_t maxPages = 0;
        std::size_t familyBytesNow = 0;
        for (const auto& pak : family->paks) {
            familyBytesNow += pak->memoryBytes();
            maxPages = std::max(maxPages, static_cast<std::uint32_t>(pak->pageOffsets.size()));
        }
        family->bytes.store(familyBytesNow, std::memory_order_relaxed);
        family->pages.resize(maxPages);
        for (const auto& pak : family->paks) {
            for (std::uint32_t page = pak->firstPage; page < pak->pageOffsets.size(); ++page) {
                const std::size_t pageOffset = pak->pageOffsets[page];
                if (pageOffset == std::numeric_limits<std::size_t>::max()) continue;
                family->pages[page] = {pak.get(), pageOffset, static_cast<std::size_t>(pak->pageSizes[page])};
            }
        }
        if (family->paks.empty()) { error = "cannot load any pak in family " + familyNames[id]; return {}; }
        profileFamily.SetBytes(familyBytesNow);
        gFamilyLoadCount.fetch_add(1, std::memory_order_relaxed);
        gFamilyLoadMicroseconds.fetch_add(static_cast<std::uint64_t>(std::chrono::duration_cast<std::chrono::microseconds>(
            std::chrono::steady_clock::now() - familyLoadStart).count()), std::memory_order_relaxed);
        std::lock_guard<std::mutex> lock(familyMutex);
        lru.push_front(id);
        families.emplace(id, CacheEntry{family, lru.begin()});
        familyBytes += familyBytesNow;
        evictLocked(id);
        return family;
    }

    // Evicts least recently used families until the cache fits its limit. A family the caller pinned (queued work still needs
    // it) and `keep` (the family that was just loaded) stay; when everything left is pinned the cache is over its limit rather
    // than thrashing.
    void evictLocked(std::uint32_t keep) {
        const std::size_t limit = gFamilyCacheLimit.load(std::memory_order_relaxed);
        for (auto it = lru.end(); familyBytes > limit && it != lru.begin();) {
            --it;
            const std::uint32_t oldId = *it;
            if (oldId == keep) continue;
            const auto pin = familyPins.find(oldId);
            if (pin != familyPins.end() && pin->second > 0) continue;
            auto old = families.find(oldId);
            if (old != families.end()) {
                familyBytes -= old->second.family->bytes;
                families.erase(old);
            }
            it = lru.erase(it);
        }
    }

    void dropCachedFamilies() {
        std::lock_guard<std::mutex> lock(familyMutex);
        families.clear();
        lru.clear();
        familyBytes = 0;
    }

    // Pins keep a family resident while the provider has queued work for it (nested calls count).
    void pinFamily(std::uint32_t id) {
        std::lock_guard<std::mutex> lock(familyMutex);
        ++familyPins[id];
    }
    void unpinFamily(std::uint32_t id) {
        std::lock_guard<std::mutex> lock(familyMutex);
        const auto pin = familyPins.find(id);
        if (pin == familyPins.end() || pin->second <= 0) return;
        if (--pin->second == 0) {
            familyPins.erase(pin);
            evictLocked(std::numeric_limits<std::uint32_t>::max());
        }
    }
    bool isFamilyLoading(std::uint32_t id) {
        std::lock_guard<std::mutex> lock(familyMutex);
        return loadingFamilies.find(id) != loadingFamilies.end();
    }
    std::size_t residentBytes(bool pinnedOnly) {
        std::lock_guard<std::mutex> lock(familyMutex);
        if (!pinnedOnly) return familyBytes;
        std::size_t total = 0;
        for (const auto& pair : families) {
            const auto pin = familyPins.find(pair.first);
            if (pin != familyPins.end() && pin->second > 0) total += pair.second.family->bytes;
        }
        return total;
    }
    // What decoding the family costs in memory (the sum of its paks' decoded sizes).
    std::size_t decodedBytes(std::uint32_t id) const {
        std::size_t total = 0;
        if (id < familyMembers.size())
            for (const std::uint32_t pakIndex : familyMembers[id]) total += static_cast<std::size_t>(paks[pakIndex].decodedSize);
        return total;
    }
};

bool ensurePaksLoaded(const Family& family, const std::vector<const PakData*>& need, std::string& error) {
    Database& db = *family.db;
    std::vector<const PakData*> todo;
    for (const PakData* pak : need)
        if (!pak->loaded.load(std::memory_order_acquire) && std::find(todo.begin(), todo.end(), pak) == todo.end()) todo.push_back(pak);
    if (todo.empty()) return true;
    db.beginLoading(family.id);
    struct LoadingGuard {
        Database& db; std::uint32_t id;
        ~LoadingGuard() { db.endLoading(id); }
    } loadingGuard{db, family.id};
    R2P_SCOPE_B(profileLoad, "d.fam.paks", db.familyNames[family.id]);
    const auto start = std::chrono::steady_clock::now();
    std::vector<std::size_t> order(todo.size());
    for (std::size_t i = 0; i < order.size(); ++i) order[i] = i;
    std::stable_sort(order.begin(), order.end(), [&](std::size_t a, std::size_t b) {
        return db.paks[todo[a]->infoIndex].fileSize > db.paks[todo[b]->infoIndex].fileSize;
    });
    std::atomic<std::size_t> added{0};
    std::mutex errorMutex;
    std::string firstError;
    runPakLoads(order, [&](std::size_t k) {
        std::size_t bytesAdded = 0;
        std::string why;
        if (!loadPakBytes(db.paks[todo[k]->infoIndex], *todo[k], bytesAdded, why)) {
            std::lock_guard<std::mutex> lock(errorMutex);
            if (firstError.empty()) firstError = why.empty() ? "pak decode failed" : why;
            return;
        }
        if (bytesAdded) {
            added.fetch_add(bytesAdded, std::memory_order_relaxed);
            db.addFamilyBytes(family, bytesAdded);
        }
    });
    profileLoad.SetBytes(added.load(std::memory_order_relaxed));
    gFamilyLoadMicroseconds.fetch_add(static_cast<std::uint64_t>(std::chrono::duration_cast<std::chrono::microseconds>(
        std::chrono::steady_clock::now() - start).count()), std::memory_order_relaxed);
    if (!firstError.empty()) { error = firstError; return false; }
    return true;
}

