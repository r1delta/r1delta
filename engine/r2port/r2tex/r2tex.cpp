bool ConvertTexture(std::string_view name, std::vector<std::uint8_t>& vtf,
                    const TextureOptions& options, std::string* error) {
    const std::string cleaned = cleanAssetName(name, true);
    if (!validAssetName(cleaned)) { vtf.clear(); if (error) *error = "invalid texture path"; return false; }
    // Synthetic names emitted by ConvertMaterial: opaque albedo aliases and expanded layer masks.
    if (cleaned.rfind(kOpaqueAlbedoPrefix, 0) == 0) {
        const std::string original = cleaned.substr(std::strlen(kOpaqueAlbedoPrefix));
        if (!validAssetName(original)) { vtf.clear(); if (error) *error = "invalid texture path"; return false; }
        TextureRef ref;
        ref.guid = textureGuid(original); ref.name = original; ref.transform = TextureTransform::opaqueAlpha;
        return ConvertTexture(ref, vtf, options, error);
    }
    if (cleaned.rfind(kNormalMapPrefix, 0) == 0) {
        const std::string original = cleaned.substr(std::strlen(kNormalMapPrefix));
        if (!validAssetName(original)) { vtf.clear(); if (error) *error = "invalid texture path"; return false; }
        TextureRef ref;
        ref.guid = textureGuid(original); ref.name = original; ref.transform = TextureTransform::normalRgb;
        return ConvertTexture(ref, vtf, options, error);
    }
    if (cleaned.rfind(kGlowRampPrefix, 0) == 0) {
        const std::string original = cleaned.substr(std::strlen(kGlowRampPrefix));
        if (!validAssetName(original)) { vtf.clear(); if (error) *error = "invalid texture path"; return false; }
        TextureRef ref;
        ref.guid = textureGuid(original); ref.name = original; ref.transform = TextureTransform::glowRamp;
        return ConvertTexture(ref, vtf, options, error);
    }
    if (cleaned.rfind(kSpecGlossPrefix, 0) == 0) {
        vtf.clear();
        std::uint64_t spc = 0, gls = 0;
        if (!parseSpecGlossName(cleaned, spc, gls)) { if (error) *error = "invalid specgloss texture path"; return false; }
        try {
            auto db = getDatabase();
            if (!db) { if (error) *error = "r2tex::Open has not succeeded"; return false; }
            std::string why;
            if (!buildSpecGlossVtf(db, spc, gls, vtf, why)) {
                vtf.clear();
                if (error) *error = "texture " + cleaned + ": " + why;
                return false;
            }
            if (error) error->clear();
            return true;
        } catch (const std::exception& e) {
            vtf.clear();
            if (error) *error = e.what();
            return false;
        }
    }
    if (cleaned.rfind(kUberPackPrefix, 0) == 0 || cleaned.rfind(kUberPackLayeredPrefix, 0) == 0) {
        vtf.clear();
        std::uint64_t mask = 0, ao = 0, cavity = 0;
        if (!parseUberPackName(cleaned, mask, ao, cavity)) { if (error) *error = "invalid uber pack texture path"; return false; }
        try {
            auto db = getDatabase();
            if (!db) { if (error) *error = "r2tex::Open has not succeeded"; return false; }
            std::string why;
            if (!buildUberPackVtf(db, mask, ao, cavity, vtf, why)) {
                vtf.clear();
                if (error) *error = "texture " + cleaned + ": " + why;
                return false;
            }
            if (error) error->clear();
            return true;
        } catch (const std::exception& e) {
            vtf.clear();
            if (error) *error = e.what();
            return false;
        }
    }
    if (cleaned.rfind(kOpacityMergePrefix, 0) == 0) {
        TextureRef ref;
        std::uint64_t opacityGuid = 0;
        if (!parseOpacityMergeName(cleaned, ref.guid, opacityGuid)) {
            vtf.clear(); if (error) *error = "invalid opacity merge texture path"; return false;
        }
        ref.name = cleaned; ref.transform = TextureTransform::opacityMerge;
        return ConvertTexture(ref, vtf, options, error);
    }
    constexpr const char* kLayerMaskPrefix = "r2tex/layer_masks/";
    if (cleaned.rfind(kLayerMaskPrefix, 0) == 0) {
        const std::string rest = cleaned.substr(std::strlen(kLayerMaskPrefix));
        const bool inverse = rest.size() == 16 + 7 && rest.compare(16, 7, "_rg_inv") == 0;
        if ((rest.size() == 16 + 3 && rest.compare(16, 3, "_rg") == 0) || inverse) {
            char* end = nullptr;
            const std::string hex = rest.substr(0, 16);
            const std::uint64_t guid = std::strtoull(hex.c_str(), &end, 16);
            if (end == hex.c_str() + 16) {
                TextureRef ref;
                ref.guid = guid; ref.name = cleaned;
                ref.transform = inverse ? TextureTransform::maskRgInv : TextureTransform::maskRg;
                return ConvertTexture(ref, vtf, options, error);
            }
        }
        vtf.clear(); if (error) *error = "invalid layer mask texture path"; return false;
    }
    // Overview images ("overviews/<map>", the R1 minimap texture) are drawn by R1's MiniMap material proxy as a
    // 0..1 texture whose coordinates run past the map edge, so they clamp (R1's own overview VTFs carry CLAMPS|CLAMPT).
    constexpr const char* kOverviewPrefix = "overviews/";
    constexpr std::uint32_t kVtfClampS = 0x4, kVtfClampT = 0x8;
    vtf.clear();
    try {
        auto db = getDatabase();
        if (!db) { if (error) *error = "r2tex::Open has not succeeded"; return false; }
        const AssetRecord* record = findTextureRecord(*db, cleaned);
        std::string why = "unresolved texture GUID";
        if (!record || !convertTextureWithDb(db, *record, options, vtf, why)) {
            vtf.clear();
            if (error) *error = "texture " + cleaned + ": " + why;
            return false;
        }
        if (cleaned.rfind(kOverviewPrefix, 0) == 0 && vtf.size() >= 0x18) {
            std::string padError;
            if (!padVtfToSquare(vtf, padError)) {
                vtf.clear();
                if (error) *error = "texture " + cleaned + ": " + padError;
                return false;
            }
            std::uint32_t flags = 0;
            std::memcpy(&flags, vtf.data() + 0x14, sizeof(flags));
            flags |= kVtfClampS | kVtfClampT;
            std::memcpy(vtf.data() + 0x14, &flags, sizeof(flags));
        }
        if (error) error->clear();
        return true;
    } catch (const std::exception& e) {
        vtf.clear();
        if (error) *error = e.what();
        return false;
    }
}

bool ConvertTexture(const TextureRef& texture, std::vector<std::uint8_t>& vtf, std::string* error) {
    return ConvertTexture(texture, vtf, TextureOptions{}, error);
}

bool ConvertTexture(const TextureRef& texture, std::vector<std::uint8_t>& vtf,
                    const TextureOptions& options, std::string* error) {
    if (texture.transform == TextureTransform::none)
        return ConvertTexture(texture.guid, vtf, options, error);
    if (texture.transform == TextureTransform::uberPack)
        return ConvertTexture(std::string_view(texture.name), vtf, options, error);
    if (texture.transform == TextureTransform::specGloss)
        return ConvertTexture(std::string_view(texture.name), vtf, options, error);
    if (texture.transform == TextureTransform::glowRamp) {
        vtf.clear();
        try {
            auto db = getDatabase();
            if (!db) { if (error) *error = "r2tex::Open has not succeeded"; return false; }
            if (!findRecord(*db, texture.guid, kTxtr)) { if (error) *error = "unresolved texture GUID"; return false; }
            buildGlowRampVtf(vtf);
            if (error) error->clear();
            return true;
        } catch (const std::exception& e) {
            vtf.clear();
            if (error) *error = e.what();
            return false;
        }
    }
    vtf.clear();
    try {
        auto db = getDatabase();
        if (!db) { if (error) *error = "r2tex::Open has not succeeded"; return false; }
        const AssetRecord* record = findRecord(*db, texture.guid, kTxtr);
        if (!record) { if (error) *error = "unresolved texture GUID"; return false; }
        TextureOptions decodeOptions = options;
        decodeOptions.bc7Passthrough = false;
        decodeOptions.bc6hPassthrough = false;
        std::string why;
        if (!convertTextureWithDb(db, *record, decodeOptions, vtf, why)) {
            if (error) *error = why;
            return false;
        }
        if (texture.transform == TextureTransform::opacityMerge) {
            std::uint64_t albedoGuid = 0, opacityGuid = 0, cavityGuid = 0;
            if (!parseOpacityMergeName(cleanAssetName(texture.name, true), albedoGuid, opacityGuid, &cavityGuid)) {
                vtf.clear();
                if (error) *error = "invalid opacity merge texture name";
                return false;
            }
            std::vector<std::uint8_t> opacityVtf, cavityVtf;
            const AssetRecord* opacityRecord = opacityGuid ? findRecord(*db, opacityGuid, kTxtr) : nullptr;
            if (opacityGuid && (!opacityRecord || !convertTextureWithDb(db, *opacityRecord, decodeOptions, opacityVtf, why))) {
                vtf.clear();
                if (error) *error = opacityRecord ? why : "unresolved opacity texture GUID";
                return false;
            }
            if (cavityGuid) {
                const AssetRecord* cavityRecord = findRecord(*db, cavityGuid, kTxtr);
                if (!cavityRecord || !convertTextureWithDb(db, *cavityRecord, decodeOptions, cavityVtf, why) ||
                    !buildFoliageVtf(vtf, opacityGuid ? &opacityVtf : nullptr, cavityVtf, why)) {
                    vtf.clear();
                    if (error) *error = cavityRecord ? why : "unresolved cavity texture GUID";
                    return false;
                }
            } else if (!mergeOpacityVtf(vtf, opacityVtf, why)) {
                vtf.clear();
                if (error) *error = why;
                return false;
            }
            if (error) error->clear();
            return true;
        }
        if (texture.transform == TextureTransform::normalRgb) {
            if (!convertNormalVtf(vtf, why)) {
                vtf.clear();
                if (error) *error = why;
                return false;
            }
            if (error) error->clear();
            return true;
        }
        const bool invert = texture.transform == TextureTransform::maskRgInv;
        if (texture.transform == TextureTransform::opaqueAlpha) {
            if (!forceOpaqueVtf(vtf, why)) {
                vtf.clear();
                if (error) *error = why;
                return false;
            }
            if (error) error->clear();
            return true;
        }
        if (texture.transform != TextureTransform::maskRg && !invert) {
            vtf.clear();
            if (error) *error = "unsupported texture transform";
            return false;
        }
        if (!expandLayerMaskVtf(vtf, invert, why)) {
            vtf.clear();
            if (error) *error = why;
            return false;
        }
        if (error) error->clear();
        return true;
    } catch (const std::exception& e) {
        vtf.clear();
        if (error) *error = e.what();
        return false;
    }
}

