// True when lump 0x1D holds at least one solid for model 0.
bool physicsHasWorldSolids(const Bytes& l, std::string* why) {
    size_t o = 0;
    bool seenTerm = false;
    while (o + 16 <= l.size()) {
        int32_t h[4];
        std::memcpy(h, &l[o], 16);
        o += 16;
        if (h[0] == -1) {
            seenTerm = true;
            break;
        }
        if (h[1] < 0 || h[2] < 0 || h[3] < 0 || o + (size_t)h[1] + (size_t)h[2] > l.size()) {
            if (why) *why = "malformed record";
            return false;
        }
        if (h[0] == 0 && h[3] >= 1) return true;
        o += (size_t)h[1] + (size_t)h[2];
    }
    if (why) *why = seenTerm ? "no solids for model 0" : "no terminator record";
    return false;
}

void convertPhysics(Ctx& c) {
    Bytes& l = c.lump[L_PHYSCOLLIDE];
    if (c.opt.physics == PhysicsMode::None) {
        c.say("[rule 12] physics (0x1D): --physics none, input lump kept (%zu bytes)", l.size());
        return;
    }
    std::string why;
    if (physicsHasWorldSolids(l, &why)) {
        c.say("[rule 12] physics (0x1D): input already has solids for model 0, kept (%zu bytes)", l.size());
        return;
    }
    size_t old = l.size();
    l.assign(kStub, kStub + sizeof(kStub));
    c.present[L_PHYSCOLLIDE] = true;
    c.say("[rule 12] physics (0x1D): input has no world solids (%s, %zu bytes); replaced by the %zu byte stub (1 solid for model 0, flat VPHY blob, contents 33570819). Not real collision: it only gives the server a valid world physics object, trace collision still comes from tricoll/brushes",
          why.c_str(), old, sizeof(kStub));
}

